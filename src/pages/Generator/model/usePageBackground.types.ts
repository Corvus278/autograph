/**
 * Что нужно предпросмотру о фоне листа: чем рисовать и какого размера лист.
 */
export type PageBackgroundView = {
  /**
   * Путь к картинке фона. `null` — фон убран или ещё не загружен.
   */
  src: string | null;

  /**
   * Ширина листа в пикселях.
   */
  width: number;

  /**
   * Высота листа в пикселях. `null` — фон убран, высоту задаёт сам текст.
   */
  height: number | null;
};
