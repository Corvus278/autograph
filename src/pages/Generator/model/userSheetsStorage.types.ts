import type { PaperSheet } from '../lib/paper/paper.types';

/**
 * Загруженный пользователем лист: экземпляр вместе с семьёй, в которую он
 * добавлен, и признаком того, что характеристики уже посчитаны.
 */
export type UserSheetRecord = {
  /**
   * Идентификатор семьи, к разлиновке которой приведён экземпляр.
   */
  familyId: string;

  /**
   * Экземпляр листа со всеми его характеристиками.
   */
  sheet: PaperSheet;

  /**
   * Характеристики уже посчитаны. `false` — лист ждёт анализа: так он
   * отличается от восстановленного из хранилища, по которому анализ повторно
   * не запускается.
   */
  isAnalyzed: boolean;
};

/**
 * Лёгкая часть записи: всё, кроме фотографии и тяжёлых карт. Лежит одним
 * списком, поэтому список листов читается без разбора самих файлов.
 */
export type UserSheetIndexEntry = Omit<PaperSheet, 'src' | 'lighting' | 'texture'> & {
  /**
   * Идентификатор семьи, к которой приписан экземпляр.
   */
  familyId: string;

  /**
   * Характеристики экземпляра посчитаны.
   */
  isAnalyzed: boolean;
};
