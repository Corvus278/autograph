import type { PaperSheet } from '../lib/paper/paper.types';

/**
 * Загруженный пользователем лист: экземпляр вместе с семьёй, в которую он
 * добавлен, и признаком того, что характеристики уже посчитаны.
 */
export type UserSheetRecord = {
  /**
   * Идентификатор семьи, в которую добавлен экземпляр.
   */
  familyId: string;

  /**
   * Экземпляр листа со всеми его характеристиками.
   */
  sheet: PaperSheet;

  /**
   * Характеристики уже посчитаны. `false` — лист ждёт анализа: так он
   * отличается от восстановленного из хранилища, по которому анализ повторно
   * не запускается.
   */
  isAnalyzed: boolean;
};

/**
 * Лёгкая часть записи: кадр и разлиновка целиком, без фотографии, тяжёлых карт
 * и полей листа, повторяющих разлиновку. Лежит одним списком, поэтому список
 * листов читается без разбора самих файлов.
 *
 * Нормировка лежит отдельно: из разлиновки листа она не выводится, а
 * отрисовка её ещё читает (`@deprecated sheet-native-ruling`).
 */
export type UserSheetIndexEntry = Pick<
  PaperSheet,
  'id' | 'label' | 'width' | 'height' | 'ruling' | 'normalizeScale'
> & {
  /**
   * Идентификатор семьи, к которой приписан экземпляр.
   */
  familyId: string;

  /**
   * Характеристики экземпляра посчитаны.
   */
  isAnalyzed: boolean;
};
