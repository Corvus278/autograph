import type { SheetPlacement } from '../lib/paper/paper.types';
import type { PageRenderParams } from '../lib/render';

import type {
  CreateMirrorSurface,
  PageDrawContext,
  PageRenderInput,
} from './pageRender.types';

/**
 * Размер снимка страницы в пикселях.
 */
export type PageImageSize = {
  /**
   * Ширина снимка.
   */
  width: number;

  /**
   * Высота снимка.
   */
  height: number;
};

/**
 * Фотография листа, которую ещё предстоит загрузить. В задании лежит путь, а
 * не картинка: узел документа границу воркера не переживает, а битмап
 * декодируется на самой границе и уезжает туда передачей владения.
 */
export type PageSheetSource = {
  /**
   * Путь к фотографии или data URL.
   */
  src: string;

  /**
   * Ширина фотографии в её собственных пикселях.
   */
  width: number;

  /**
   * Высота фотографии в её собственных пикселях.
   */
  height: number;

  /**
   * Фотографию нужно отразить по горизонтали — правая половина разворота.
   */
  isMirrored: boolean;

  /**
   * Прямоугольник фотографии на странице в канонических пикселях семьи:
   * нормировка к канону разлиновки уже посчитана. Едет в задании готовой, а не
   * считается у рисующего: тот же прямоугольник берёт предпросмотр, и
   * расходиться им нельзя.
   */
  placement: SheetPlacement;
};

/**
 * Шрифт страницы для того, кто рисует. Контуры шрифта — замыкания над
 * разобранным файлом, и через границу воркера они не проходят: едет адрес
 * файла, а разбирает его тот, кто рисует.
 */
export type PageFontSource = {
  /**
   * Семейство шрифта: под этим именем разобранный файл кэшируется.
   */
  family: string;

  /**
   * Путь к файлу `.ttf`.
   */
  url: string;

  /**
   * Деформировать ли контур каждого экземпляра буквы.
   */
  hasVariance: boolean;
};

/**
 * Задание на отрисовку одной страницы прогона.
 *
 * Всё, что лежит в `params`, переживает structured clone: узлов документа,
 * картинок и функций там нет. Ресурсы — фотография листа, карта текстуры и
 * контуры шрифта — перечислены отдельными полями и подставляются в параметры
 * уже там, где страница рисуется.
 */
export type PageRenderTask = {
  /**
   * Параметры отрисовки без ресурсов: фон, карта текстуры и контуры в них
   * пусты.
   */
  params: PageRenderParams;

  /**
   * Фотография листа. `null` — фон скрыт или экземпляр не выбран.
   */
  sheet: PageSheetSource | null;

  /**
   * Путь к карте текстуры листа. `null` — карты нет.
   */
  textureSrc: string | null;

  /**
   * Шрифт страницы. `null` — контуров нет: свой шрифт пользователя приходит
   * файлом в браузер, и читать по адресу нечего.
   */
  font: PageFontSource | null;

  /**
   * Ширина страницы в канонических пикселях семьи.
   */
  pageWidth: number;

  /**
   * Высота страницы в канонических пикселях семьи.
   */
  pageHeight: number;

  /**
   * Качество кодирования от 0 до 1.
   */
  quality: number;
};

/**
 * Вход сборки задания. Всё то же, что нужно параметрам отрисовки, но вместо
 * готовых ресурсов — их адреса: задание собирается там, где ресурсов ещё нет.
 */
export type PageTaskInput = Omit<PageRenderInput, 'sheetImage' | 'ink' | 'glyphs'> & {
  /**
   * Фон скрыт пользователем: рисуются одни чернила.
   */
  isBackgroundHidden: boolean;

  /**
   * Seed прогона: из него выводится синтетическое освещение листа.
   */
  runSeed: number;

  /**
   * Шрифт страницы. `null` — контуров нет.
   */
  font: PageFontSource | null;

  /**
   * Качество кодирования от 0 до 1.
   */
  quality: number;
};

/**
 * План отрисовки прогона: сколько страниц и чем рисуется каждая.
 */
export type RunRenderPlan = {
  /**
   * Число страниц прогона.
   */
  pageCount: number;

  /**
   * Номер текущей страницы, считая с нуля: её сохраняет отдельное действие.
   */
  pageIndex: number;

  /**
   * Собирает задание на отрисовку страницы прогона.
   */
  buildTask: (pageIndex: number) => PageRenderTask;
};

/**
 * Чем кодировать нарисованное.
 */
export type PageBlobOptions = {
  /**
   * Тип содержимого файла.
   */
  type: string;

  /**
   * Качество кодирования от 0 до 1.
   */
  quality: number;
};

/**
 * Поверхность, которая отдаёт нарисованное готовым файлом. Под неё подходит
 * `OffscreenCanvas` целиком; тест подставляет запись вызовов.
 */
export type PageBlobSurface = {
  /**
   * Контекст рисования. `null` — контекст не дали.
   */
  getContext: (contextId: '2d') => PageDrawContext | null;

  /**
   * Кодирует нарисованное в файл.
   */
  convertToBlob: (options: PageBlobOptions) => Promise<Blob>;
};

/**
 * Чем отрисовка задания создаёт поверхности: одну под страницу, другую под
 * отражение фотографии. Обе подменяются в тестах — растра ни в node, ни в
 * jsdom нет.
 */
export type PageRenderSurfaces = {
  /**
   * Создаёт поверхность страницы.
   */
  createPage: (width: number, height: number) => PageBlobSurface;

  /**
   * Создаёт поверхность отражения фотографии.
   */
  createMirror: CreateMirrorSurface;
};
