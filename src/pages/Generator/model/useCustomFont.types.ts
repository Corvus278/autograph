/**
 * Загрузка пользовательского шрифта: состояние ошибки и методы работы с ним.
 */
export type CustomFontControl = {
  /**
   * Сообщение об ошибке разбора файла. `null` — ошибки нет.
   */
  error: string | null;

  /**
   * Загружает шрифт из файла и делает его активным.
   */
  load: (file: File) => Promise<void>;

  /**
   * Возвращает текст к шрифту, выбранному в списке.
   */
  reset: () => void;
};
