/**
 * Отрисовка одной страницы в готовый файл изображения. Индекс страницы —
 * с нуля: так же нумерует страницы рецепт прогона (`lib/recipe`).
 *
 * Сигнал отмены передаётся дальше, чтобы отрисовка полного разрешения могла
 * оборваться на середине, а не дорисовывать страницу впустую. Отказ обещания —
 * неудача одной страницы: пачка на ней не останавливается.
 */
export type RenderPageBlob = (
  pageIndex: number,
  signal?: AbortSignal | undefined
) => Promise<Blob>;

/**
 * Сколько страниц пройдено и сколько их всего.
 */
export type BatchProgress = {
  /**
   * Число пройденных страниц. Неудавшаяся страница тоже увеличивает счётчик:
   * иначе прогресс замер бы на ней до конца выгрузки.
   */
  completed: number;

  /**
   * Общее число страниц прогона.
   */
  total: number;
};

/**
 * Колбэк прогресса. Дёргается один раз в начале с нулём готовых и по разу
 * после каждой пройденной страницы.
 */
export type BatchProgressCallback = (progress: BatchProgress) => void;

/**
 * Упаковщик пачки: принимает страницы по одной в порядке отрисовки и в конце
 * собирает архив. Потоковость держится на нём — оркестратор блобы не копит.
 */
export type BatchPacker = {
  /**
   * Принимает очередную страницу. Обещание разрешается, когда страница принята:
   * после этого оркестратор ссылку на блоб не держит. Отказ — страница в архив
   * не попала.
   */
  addPage: (pageIndex: number, page: Blob) => Promise<void>;

  /**
   * Собирает архив из принятых страниц.
   */
  build: () => Promise<Blob>;
};

/**
 * Вход прогона пачки.
 */
export type GeneratePageBatchParams = {
  /**
   * Число страниц прогона.
   */
  pageCount: number;

  /**
   * Чем отрисовывается одна страница.
   */
  renderPage: RenderPageBlob;

  /**
   * Куда складываются готовые страницы. По умолчанию — zip-упаковщик
   * (`packPagesToZip.ts`); подменяется в тестах и под другой формат архива.
   */
  packer?: BatchPacker | undefined;

  /**
   * Куда сообщать прогресс.
   */
  onProgress?: BatchProgressCallback | undefined;

  /**
   * Сигнал отмены. Проверяется между страницами и после сборки архива, а также
   * передаётся в отрисовку страницы. Отменённый прогон архив не отдаёт и
   * исключением не завершается.
   */
  signal?: AbortSignal | undefined;
};

/**
 * Отчёт о прогоне пачки.
 */
export type PageBatchReport = {
  /**
   * Готовый архив. `null` — скачивать нечего: прогон отменён, сборка не
   * удалась или в архив не попало ни одной страницы.
   */
  archive: Blob | null;

  /**
   * Признак отмены: прогон прерван сигналом, а не дошёл до конца.
   */
  isCanceled: boolean;

  /**
   * Признак сбоя сборки архива: страницы были, но архив не собрался.
   */
  hasBuildError: boolean;

  /**
   * Индексы страниц, не попавших в архив, считая с нуля — как `pageIndex`
   * рецепта прогона.
   */
  failedPageIndexes: number[];

  /**
   * Те же страницы номерами с единицы — как в именах файлов архива и как их
   * видит пользователь.
   */
  failedPageNumbers: number[];

  /**
   * Сколько страниц принял упаковщик.
   */
  packedCount: number;
};

/**
 * Вход zip-упаковщика.
 */
export type ZipPackerParams = {
  /**
   * Общее число страниц прогона: по нему считается ширина номера в имени
   * файла, чтобы имена сортировались лексикографически по номеру страницы.
   */
  totalPages: number;
};

/**
 * Вход сборки имени файла страницы в архиве.
 */
export type PageFileNameParams = {
  /**
   * Номер страницы, считая с единицы.
   */
  pageNumber: number;

  /**
   * Общее число страниц прогона.
   */
  totalPages: number;

  /**
   * Тип содержимого страницы: из него берётся расширение файла.
   */
  mimeType: string;
};
