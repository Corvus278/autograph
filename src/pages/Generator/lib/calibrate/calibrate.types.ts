import type { PaperRuling } from '../paper/paper.types';

/**
 * Разлиновка вместе с шириной канонического листа семьи. Ширина нужна
 * отдельным полем: правое поле задано отступом от правого края, и без ширины
 * листа ширину блока текста не вывести.
 */
export type CalibrationRuling = PaperRuling & {
  /**
   * Ширина канонического листа семьи в пикселях.
   */
  pageWidth: number;
};

/**
 * Геометрия блока текста в канонических пикселях семьи. Пиксели, а не em:
 * `em` — единица DOM, и появляется она только на границе со стилями.
 */
export type BlockGeometry = {
  /**
   * Кегль в пикселях.
   */
  fontSizePx: number;

  /**
   * Добавка к естественной высоте строки в пикселях. Отрицательная сжимает
   * строки: у рукописных шрифтов строчный бокс обычно выше шага разлиновки.
   */
  lineSpacing: number;

  /**
   * Отступ верха первой строки от верха листа в пикселях.
   */
  topOffset: number;

  /**
   * Отступ блока текста от левого края листа в пикселях.
   */
  leftPadding: number;

  /**
   * Ширина блока текста в пикселях: по ней считается перенос по словам.
   */
  blockWidth: number;
};

/**
 * Ручная поправка: дельты поверх вычисленной геометрии. Именно дельты, а не
 * значения — поправка переживает смену экземпляра листа и смену семьи, потому
 * что применяется к заново вычисленному.
 */
export type GeometryCorrection = {
  /**
   * Дельта кегля в пикселях.
   */
  fontSizePx?: number;

  /**
   * Дельта межстрочного интервала в пикселях.
   */
  lineSpacing?: number;

  /**
   * Дельта верхнего отступа в пикселях.
   */
  topOffset?: number;

  /**
   * Дельта левого отступа в пикселях.
   */
  leftPadding?: number;

  /**
   * Дельта ширины блока в пикселях.
   */
  blockWidth?: number;
};
