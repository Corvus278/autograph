import type { PaperFamily } from '../paper/paper.types';
import type { DistortionFlags } from '../randomize/randomize.types';

/**
 * Цвет реального пишущего средства. Палитра держит именно оттенки ручек:
 * случайный цвет берётся из них, а не из всего цветового пространства.
 */
export type InkTone = {
  /**
   * Идентификатор оттенка, уникальный внутри палитры.
   */
  id: string;

  /**
   * Подпись оттенка: чем он написан в жизни.
   */
  label: string;

  /**
   * Цвет в формате `#rrggbb`.
   */
  color: string;
};

/**
 * Что достаётся одной странице прогона. Страницы лежат по порядку: индекс в
 * массиве — номер страницы, считая с нуля.
 */
export type PageRecipe = {
  /**
   * Номер страницы, считая с нуля.
   */
  pageIndex: number;

  /**
   * Идентификатор экземпляра листа из выбранной семьи.
   */
  sheetId: string;

  /**
   * Seed шума, деформирующего контуры глифов на этой странице. Свой на
   * страницу: иначе одинаковый текст на разных страницах получил бы
   * одинаковые случайные контуры.
   */
  contourSeed: number;
};

/**
 * Параметры неровности почерка: рисунок искажений плюс то, как густо они
 * ложатся.
 */
export type HandwritingRecipe = {
  /**
   * Seed искажений почерка — вход `lib/randomize`.
   */
  seed: number;

  /**
   * Включённые виды искажений. Задаются пользователем, прогоном не
   * перекрываются.
   */
  flags: DistortionFlags;

  /**
   * Как часто слово попадает под побуквенную обработку: 1 — каждое
   * подходящее, дальше реже.
   */
  wordFrequency: number;

  /**
   * Верхняя граница числа искажаемых букв в слове.
   */
  letterFrequency: number;
};

/**
 * Параметры вариативности контуров глифов: одинаковые буквы расходятся по
 * форме на этих величинах. Seed вариативности живёт на странице —
 * `PageRecipe.contourSeed`.
 */
export type ContourRecipe = {
  /**
   * Амплитуда смещения контрольных точек контура в долях em.
   */
  amplitude: number;

  /**
   * Размер ячейки решётки шума в долях em: на её узлах берётся смещение,
   * между узлами — сглаживается.
   */
  cellSize: number;
};

/**
 * Параметры оптики страницы: чем страница растеризуется в файл. Разрешения
 * здесь нет: снимок равен кадру листа страницы, и масштаб — величина страницы,
 * а не прогона.
 */
export type PageOpticsRecipe = {
  /**
   * Качество кодирования JPEG от 0 до 1.
   */
  jpegQuality: number;
};

/**
 * Рецепт прогона: единственный источник случайности отрисовки. Всё в нём
 * выведено из `seed`, поэтому прогон с тем же seed повторяется целиком.
 */
export type RunRecipe = {
  /**
   * Seed прогона — число, из которого выведено всё остальное.
   */
  seed: number;

  /**
   * Семья листов, внутри которой выбирались экземпляры. Рецепт её не
   * подменяет: семью задаёт пользователь.
   */
  familyId: string;

  /**
   * Цвет чернил всего прогона в формате `#rrggbb`.
   */
  inkColor: string;

  /**
   * Страницы прогона по порядку.
   */
  pages: PageRecipe[];

  /**
   * Параметры неровности почерка.
   */
  handwriting: HandwritingRecipe;

  /**
   * Параметры вариативности контуров.
   */
  contour: ContourRecipe;

  /**
   * Параметры оптики страницы.
   */
  optics: PageOpticsRecipe;
};

/**
 * Вход сборки рецепта. Всё, что здесь задано пользователем, рецепт передаёт
 * дальше как есть; случайным остаётся только то, что выводится из seed.
 */
export type BuildRunRecipeParams = {
  /**
   * Seed прогона.
   */
  seed: number;

  /**
   * Выбранная пользователем семья листов.
   */
  family: PaperFamily;

  /**
   * Число страниц прогона.
   */
  pageCount: number;

  /**
   * Включённые виды искажений почерка.
   */
  flags: DistortionFlags;

  /**
   * Цвет чернил, заданный пользователем вручную. `null` — взять из палитры.
   */
  inkColor: string | null;

  /**
   * Частота побуквенной обработки слов, заданная пользователем. `null` или
   * отсутствие — вывести из seed.
   */
  wordFrequency?: number | null;

  /**
   * Ограничение на число искажаемых букв в слове, заданное пользователем.
   * `null` или отсутствие — вывести из seed.
   */
  letterFrequency?: number | null;
};
