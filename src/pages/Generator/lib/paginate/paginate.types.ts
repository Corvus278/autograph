import type { GeometryCorrection, SheetCalibration } from '../calibrate/calibrate.types';
import type { FontMetrics, TextMeasurer } from '../measure/measure.types';
import type { Line } from '../split/splitParagraphs.types';

/**
 * Страница — набор строк, помещающихся на лист. Строка целиком принадлежит
 * одной странице: пополам её не режем.
 */
export type Page = {
  /**
   * Строки страницы в порядке отрисовки. Пустой массив — пустая страница,
   * такая получается, пока раскладка не посчитана.
   */
  lines: Line[];
};

/**
 * Страница последовательной раскладки: строки набраны под лист, доставшийся
 * странице, и лист едет вместе с ними — отрисовка берёт тот же лист, по
 * которому считались перенос и вместимость.
 */
export type LayoutPage = Page & {
  /**
   * Идентификатор экземпляра листа, под разлиновку которого набрана страница.
   */
  sheetId: string;
};

/**
 * Лист страницы так, как его видит разбивка.
 */
export type PageSheet = {
  /**
   * Идентификатор экземпляра листа.
   */
  sheetId: string;

  /**
   * Разлиновка страницы и кадр её листа; на зеркальной странице разлиновка
   * приходит уже отражённой.
   */
  calibration: SheetCalibration;
};

export type PaginateOptions = {
  /**
   * Измеритель ширин в долях кегля.
   */
  measure: TextMeasurer;

  /**
   * Метрики шрифта в долях кегля: по ним выводятся геометрия блока и шаг
   * строк.
   */
  metrics: FontMetrics;

  /**
   * Ручная поправка геометрии в долях шага разлиновки.
   */
  correction: GeometryCorrection;

  /**
   * Запас снизу в долях шага разлиновки листа страницы.
   */
  bottomMargin: number;

  /**
   * Лист страницы по её номеру. Страницы запрашиваются по порядку, по разу на
   * страницу, поэтому раздача листов может наращиваться по мере надобности.
   */
  getPageSheet: (pageIndex: number) => PageSheet;
};
