import type { LightingField } from '../paper/paper.types';

/**
 * Цвет чернил по каналам. Значения — от 0 до 255, дробные допустимы:
 * модуляция умножает канал на коэффициент, а округление до байта — дело
 * растеризатора, а не формулы.
 */
export type InkRgb = {
  /**
   * Красный канал, 0…255.
   */
  red: number;

  /**
   * Зелёный канал, 0…255.
   */
  green: number;

  /**
   * Синий канал, 0…255.
   */
  blue: number;
};

/**
 * Коэффициенты модуляции чернил, заполненные целиком. Один и тот же набор
 * подставляется в CPU-формулу и в текст шейдера, поэтому у него отдельный тип
 * без необязательных полей.
 */
export type InkModulation = {
  /**
   * Доля, на которую самая тёмная часть листа гасит чернила: при освещении 0
   * коэффициент чернил падает на эту величину.
   */
  lightInfluence: number;

  /**
   * Доля, на которую самая тёмная точка текстуры гасит чернила относительно
   * самой светлой.
   */
  textureInfluence: number;

  /**
   * Нижняя граница коэффициента: насколько тёмными чернила имеют право стать
   * от исходного цвета. Держит след от ухода в чистый чёрный.
   */
  minGain: number;
};

/**
 * Те же коэффициенты, но каждый необязателен: вызывающая сторона правит
 * только то, что хочет отклонить от значений по умолчанию.
 */
export type InkModulationOptions = {
  /**
   * Доля, на которую самая тёмная часть листа гасит чернила.
   */
  lightInfluence?: number;

  /**
   * Доля, на которую самая тёмная точка текстуры гасит чернила.
   */
  textureInfluence?: number;

  /**
   * Нижняя граница коэффициента модуляции.
   */
  minGain?: number;
};

/**
 * Всё, что нужно шейдеру, чтобы промодулировать отрисованный слой чернил.
 */
export type InkLayerParams = {
  /**
   * Отрисованный слой чернил: канва страницы, `ImageBitmap` или любой другой
   * источник, пригодный для загрузки в текстуру.
   */
  inkLayer: TexImageSource;

  /**
   * Ширина слоя в пикселях.
   */
  width: number;

  /**
   * Высота слоя в пикселях.
   */
  height: number;

  /**
   * Поле освещения экземпляра листа. `null` или поле с `isUsable: false`
   * заменяются синтетическим освещением.
   */
  lighting: LightingField | null;

  /**
   * Карта текстуры листа как изображение: 0.5 в канале — нулевое отклонение.
   * `null` — текстуры нет, чернила модулируются одним освещением.
   */
  textureImage: TexImageSource | null;

  /**
   * Seed прогона: из него выводится синтетическое освещение, поэтому один и
   * тот же прогон освещён одинаково при каждой отрисовке.
   */
  seed: number;

  /**
   * Отклонения от коэффициентов по умолчанию.
   */
  options?: InkModulationOptions;
};
