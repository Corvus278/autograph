/**
 * Измеритель текста. Ядро генератора не трогает DOM само: и перенос по словам,
 * и разбивка на страницы спрашивают размеры здесь. В приложении измеряет
 * настоящий скрытый контейнер, в тестах — модель с фиксированной шириной
 * символа.
 */
export type TextMeasurer = {
  /**
   * Ширина фрагмента в пикселях, как он отрисуется текущим шрифтом.
   */
  measureWidth: (text: string) => number;

  /**
   * Высота одной строки в пикселях с учётом межстрочного интервала.
   */
  measureLineHeight: () => number;
};

/**
 * То, что нужно от `document.fonts`: запросить конкретное начертание и
 * дождаться готовности шрифтов документа. Сужение позволяет подменять источник
 * в тестах.
 */
export type FontsReadySource = Pick<FontFaceSet, 'load' | 'ready'>;

/**
 * Измеритель на живом DOM. Держит скрытый контейнер, поэтому его нужно убирать
 * за собой, когда параметры отрисовки поменялись.
 */
export type DomMeasurer = TextMeasurer & {
  /**
   * Убирает скрытый контейнер из документа и сбрасывает кэш ширин.
   */
  destroy: () => void;
};

/**
 * Настройки отрисовки, при которых снимаются размеры. Совпадают с тем, что
 * применяется к тексту страницы, иначе переносы разъедутся с отрисовкой.
 */
export type MeasurerParams = {
  /**
   * Семейство шрифта, которым набран текст.
   */
  fontFamily: string;

  /**
   * Размер шрифта в em — в тех же единицах, что и слайдер размера.
   */
  fontSize: number;

  /**
   * Добавка к межстрочному интервалу в пикселях. Отрицательная сжимает строки.
   */
  lineSpacing: number;
};

/**
 * Метрики шрифта в долях кегля. Доли, а не пиксели: кегль автокалибровка как
 * раз и подбирает, а пропорции начертания от него не зависят.
 */
export type FontMetrics = {
  /**
   * Высота строчных без выносных элементов (x-height) в долях кегля.
   */
  xHeight: number;

  /**
   * Подъём строчного бокса над базовой линией в долях кегля: расстояние от
   * верха бокса, а не от верха чернил. Именно от него отсчитывается верхний
   * отступ блока — чернильный подъём заметно меньше и увёл бы первую строку
   * выше линии.
   */
  fontAscent: number;

  /**
   * Естественная высота строки (`line-height: normal`) в долях кегля: подъём
   * плюс спуск строчного бокса. По ней считается добавка к межстрочному
   * интервалу.
   */
  lineHeight: number;
};

/**
 * Щуп метрик: вертикальный собрат `TextMeasurer`. Высоту строки отдаёт тем же
 * методом, что и измеритель текста, остальное снимает сам — по ширине
 * фрагмента высоту не восстановить.
 *
 * Ядро метрик DOM не трогает: в приложении щуп меряет настоящим шрифтом, в
 * тестах подставляется модель с заданными пропорциями.
 */
export type FontMetricsProbe = Pick<TextMeasurer, 'measureLineHeight'> & {
  /**
   * Подъём чернил фрагмента над базовой линией в пикселях. По строчным без
   * выносных элементов это и есть высота строчных.
   */
  measureInkAscent: (sample: string) => number;

  /**
   * Подъём строчного бокса шрифта над базовой линией в пикселях. От текста не
   * зависит: это метрика начертания, а не фрагмента.
   */
  measureFontAscent: () => number;

  /**
   * Кегль в пикселях, которым набраны измеряемые фрагменты.
   */
  fontSizePx: number;
};

/**
 * Создаёт щуп для конкретного семейства шрифта.
 */
export type FontMetricsProbeFactory = (fontFamily: string) => FontMetricsProbe | null;
