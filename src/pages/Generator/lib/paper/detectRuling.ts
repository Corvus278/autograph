/**
 * Разлиновка вместе со стороной, у которой нашлась линия поля.
 *
 * Сторона нужна отдельно от `marginLineX`: одного смещения мало, чтобы понять,
 * левая это половина разворота или правая, а от этого зависит, куда класть
 * блок текста на чётной странице. Поле объявлено здесь, а не в
 * `paper.types.ts`: `RulingDetection` ведёт владелец public API, к нему заявка
 * на `marginLineSide`.
 */
export type DetectedRuling = RulingDetection & {
  /**
   * Край, у которого стоит линия поля. `null` — линии поля нет.
   */
  marginLineSide: MarginLineSide | null;

  /**
   * Доля узлов области с линиями, где при измерении изгиба линия нашлась, от 0
   * до 1. Есть и при `bend: null`: по ней сборка профилей показывает, почему
   * изгиб отброшен, и сверяет пороги надёжности.
   */
  bendFoundNodeShare: number;

  /**
   * Наклон в градусах, при котором измерена разлиновка: заданный в настройках
   * или найденный свипом. Есть и у ненайденной разлиновки: импорт кладёт его в
   * лист, ждущий ручного ввода.
   */
  skewAngle: number;

  /**
   * Поля по ядру разлиновки — линиям, подтверждённым опросом у прямой гребёнки.
   * Боковые совпадают с `margins`, верхнее и нижнее могут лечь внутрь них: трасса
   * вдоль линий удерживает крайние линии, ушедшие от прямой гребёнки на волне, а
   * перспективу по ним подгонять нельзя — волна не описывается её моделью.
   */
  coreMargins: PaperMargins;

  /**
   * Крайние линии области, упёршейся в край профиля: там поле не найдено, и
   * `margins` держит ноль. Край профиля вырезки внутри листа — ещё не край
   * листа, и по этим линиям измерение фотографии проверяет, есть ли линии за
   * краем вырезки.
   */
  ruledEdges: RuledEdges;

  /**
   * Что сделала полосовая ступень: не понадобилась, отказала или дала шаг.
   *
   * Поле живёт в `DetectedRuling`, а не в `RulingDetection`: полосы — ступень
   * измерения, а не характеристика листа, и в формат хранения не попадают.
   */
  bandedStage: RulingBandedStage;

  /**
   * Ступень поиска линии поля и числа полосового опроса.
   *
   * Поле живёт в `DetectedRuling`, а не в `RulingDetection`: это отчёт о том,
   * как измерение пришло к своему числу, а не характеристика листа, и в
   * формат хранения оно не попадает.
   */
  marginLineReport: MarginLineReport;

  /**
   * Шаги полос кадра, поперёк линий, сверху вниз, в пикселях изображения.
   * Пусто у любой ступени, кроме `measured`.
   */
  bandSteps: number[];

  /**
   * Засев схождения `k` из `step(u) = step·(1 + k·(u − convergenceOrigin))`,
   * 1/px: во сколько раз на пиксель координаты вдоль линий растёт шаг. `0` —
   * шаг пришёл не от полос либо шаг по кадру не меняется.
   */
  convergenceSeed: number;

  /**
   * Начало отсчёта координаты вдоль линий, от которого взяты `step` и
   * `convergenceSeed`, в пикселях изображения: середина области с линиями в
   * столбце `x = 0`.
   *
   * Идёт наружу вместе с засевом, потому что потребитель отсчитывает свою
   * координату от середины кадра: перенос `step(u)` с чужим началом ошибается
   * на `k·Δ`, а `Δ` у листа с линиями в части кадра — не ноль. `0` у любой
   * ступени, кроме `measured`.
   */
  convergenceOrigin: number;
};

