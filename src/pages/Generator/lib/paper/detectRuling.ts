/**
 * Ищет одиночную вертикальную линию поля у левого и у правого края кадра.
 *
 * С обеих сторон, а не только слева: лист может быть снят как правая половина
 * разворота, и тогда поле оказывается справа. На восьми снимках пресет-пака
 * линия стоит именно справа, на доле ширины от 0.85 до 0.91.
 *
 * Линия видна как провал средней яркости столбца, который глубже и обычного
 * шума, и обычных вертикальных линий листа: на клетчатом листе иначе за линию
 * поля сошла бы любая линия клетки. Поэтому глубина кандидата сравнивается с
 * глубиной линий из средней трети — там линия поля не встречается, а клетка
 * есть.
 *
 * Линия поля цветная, обычно красная, а на вход приходит яркость. Красное на
 * белом даёт провал мельче, чем то же самое в зелёном канале: на снимках
 * пресет-пака яркостный провал держится на уровне 0.20…0.28, зелёный — на
 * 0.22…0.35, то есть яркость теряет около четверти глубины. Запаса до порога
 * это не съедает, но если однажды понадобится ловить бледную линию, цветной
 * канал — готовый источник: `SheetImageData` придётся расширить до цвета.
 *
 * @param columns — профиль средней яркости по столбцам
 * @param step — шаг разлиновки в пикселях
 * @param width — ширина кадра в пикселях
 * @param side — край, которым ограничен поиск; не задан — оба
 * @returns линия и сторона, у которой она стоит; `null` — линии поля нет
 */
const findMarginLine = (
  columns: ShearedProfile,
  step: number,
  width: number,
  side?: MarginLineSide
): MarginLine | null => {
  const { values, origin } = columns;
  const size = values.length;
  const leftEnd = Math.ceil(width * MARGIN_LINE_SEARCH_FRACTION) - origin;
  const rightStart = Math.floor(width * (1 - MARGIN_LINE_SEARCH_FRACTION)) - origin;

  if (size < 8 || leftEnd < 2 || rightStart > size - 2) {
    return null;
  }

  const background = computeMovingMedian(values, toBackgroundWindow(step));
  const depth = new Float64Array(size);

  for (let index = 0; index < size; index += 1) {
    depth[index] = (background[index] || 0) - (values[index] || 0);
  }

  const deviations: number[] = [];
  const middlePeaks: number[] = [];
  let leftIndex = -1;
  let rightIndex = -1;

  for (let index = 1; index < size - 1; index += 1) {
    deviations.push(Math.abs(depth[index] || 0));

    if (!isDepthPeak(depth, index)) {
      continue;
    }

    if (index < leftEnd) {
      if (leftIndex < 0 || (depth[index] || 0) > (depth[leftIndex] || 0)) {
        leftIndex = index;
      }

      continue;
    }

    if (index > rightStart) {
      if (rightIndex < 0 || (depth[index] || 0) > (depth[rightIndex] || 0)) {
        rightIndex = index;
      }

      continue;
    }

    middlePeaks.push(depth[index] || 0);
  }

  const sigma = NORMAL_MAD_FACTOR * computeMedian(deviations);
  const { value: threshold } = toMarginLineBarrier(
    computeQuantile(middlePeaks, MARGIN_LINE_PEER_QUANTILE),
    sigma
  );
  const leftDepth = leftIndex < 0 ? 0 : depth[leftIndex] || 0;
  const rightDepth = rightIndex < 0 ? 0 : depth[rightIndex] || 0;
  /**
   * Заданная сторона выбирает кандидата вместо сравнения глубин: кандидат с
   * другого края не участвует в отборе, а не отсеивается после него.
   */
  const isLeft = side === undefined ? leftDepth >= rightDepth : side === 'left';
  const bestIndex = isLeft ? leftIndex : rightIndex;

  if (bestIndex < 0 || (isLeft ? leftDepth : rightDepth) < threshold) {
    return null;
  }

  const offset = refinePeakOffset(
    depth[bestIndex - 1] || 0,
    depth[bestIndex] || 0,
    depth[bestIndex + 1] || 0
  );

  return { x: origin + bestIndex + offset, side: isLeft ? 'left' : 'right' };
};

const detrendStrips = (strips: ShearedProfile[], step: number): Float64Array[] => {
  return strips.map((strip) => {
    return detrendProfile(strip.values, 2 * Math.round(step) + 1);
  });
};

const toLineReach = (step: number): number => {
  return Math.max(1, Math.round(step * LINE_SEARCH_SHARE));
};

/**
 * Опрашивает профили полос в предсказанных положениях линий гребёнки.
 *
 * Глубина линии берётся в окне вокруг предсказанного положения, а не в самом
 * бине: линии у края кадра уходят с гребёнки, и без окна цепочка рвалась бы
 * перед ними. Окно меряется в каждой полосе отдельно, и глубиной линии служит
 * медиана по полосам.
 *
 * @param detrendedStrips — профили полос без фона с общими бинами
 * @param origin — координата нулевого бина в пикселях фотографии
 * @param step — шаг гребёнки в пикселях
 * @param phase — смещение линий по модулю шага
 * @returns координаты и глубины линий, попавших в профиль, по порядку
 */
const measureCombDepths = (
  detrendedStrips: Float64Array[],
  origin: number,
  step: number,
  phase: number
): CombDepths => {
  const size = detrendedStrips[0]?.length || 0;
  const firstLine = Math.ceil((origin - phase) / step);
  const lastLine = Math.floor((origin + size - 1 - phase) / step);
  const reach = toLineReach(step);
  const positions: number[] = [];
  const depths: number[] = [];

  for (let line = firstLine; line <= lastLine; line += 1) {
    const coordinate = phase + line * step;
    const bin = Math.round(coordinate) - origin;

    positions.push(coordinate);
    depths.push(
      computeMedian(
        detrendedStrips.map((detrended) => {
          return measureLineDepth(detrended, bin, reach);
        })
      )
    );
  }

  return { positions, depths };
};

/**
 * Прослеживает линии гребёнки по полосам вдоль самих линий
 * (`traceRulingLines`): линия, ушедшая от прямой гребёнки на волне листа или
 * в перспективе дальше окна опроса, остаётся своей, и цепочка у края области
 * не рвётся перед ней.
 *
 * Глубина линии — медиана по полосам, где полоса без линии даёт ноль. Край
 * профиля — линия, окно поиска которой не помещается в профиль в большинстве
 * полос: у неё отсутствие провала ничего не говорит о листе.
 *
 * @param detrendedStrips — профили полос без фона с общими бинами
 * @param origin — координата нулевого бина в пикселях фотографии
 * @param step — шаг гребёнки в пикселях
 * @param phase — смещение линий по модулю шага
 * @returns линии прямой гребёнки, попавшие в профиль, с глубинами и
 *   положениями по полосам
 */
const traceCombDepths = (
  detrendedStrips: Float64Array[],
  origin: number,
  step: number,
  phase: number
): TracedComb => {
  const size = detrendedStrips[0]?.length || 0;
  const firstLine = Math.ceil((origin - phase) / step);
  const lastLine = Math.floor((origin + size - 1 - phase) / step);
  const count = Math.max(0, lastLine - firstLine + 1);
  const reach = step * TRACE_SEARCH_SHARE;
  const traced = traceRulingLines(detrendedStrips, {
    lineOffset: phase - origin,
    step,
    firstLine,
    lastLine,
    middleLine: Math.round((size / 2 + origin - phase) / step),
  });
  const positions = Array.from({ length: count }, (_item, index) => {
    return phase + (firstLine + index) * step;
  });

  if (traced === null) {
    return {
      positions,
      depths: positions.map(() => {
        return 0;
      }),
      stripPositions: positions.map(() => {
        return [];
      }),
      measurable: positions.map(() => {
        return true;
      }),
    };
  }

  return {
    positions,
    depths: traced.map((line) => {
      return computeMedian(
        line.map(({ dip }) => {
          return dip === null ? 0 : dip.depth;
        })
      );
    }),
    stripPositions: traced.map((line) => {
      return line.map(({ dip }) => {
        return dip === null ? null : origin + dip.position;
      });
    }),
    measurable: traced.map((line) => {
      const outside = line.reduce((total, { predicted }) => {
        return predicted - reach < 1 || predicted + reach > size - 2 ? total + 1 : total;
      }, 0);

      return outside * 2 < line.length;
    }),
  };
};

/**
 * Профиль полосы вместе с мерой глубины провала в её бинах.
 *
 * Мера спрятана за функцией, потому что её потребителям нужны разные доли
 * полосы: полосовому опросу — все бины разом, трассе линии — только окна
 * вокруг предсказаний, сотые доли полосы. Проход по всей полосе ради трассы
 * стоил бы дороже самой трассы, а счёт медианы заново в каждом бине опроса —
 * дороже прохода. Числа у обеих мер одни: скользящая медиана в бине — та же
 * медиана того же окна.
 */
type StripDepths = {
  /**
   * Глубина провала в бине полосы: насколько бин темнее скользящей медианы
   * окном в шаг. Бин за пределами полосы — ноль.
   */
  depthAt: (bin: number) => number;

  /**
   * Профиль столбцов полосы.
   */
  strip: ShearedProfile;
};

/**
 * Полоса, у которой глубины всех бинов уже сняты: полосовому опросу нужен
 * весь ряд разом — и на пики, и на разброс.
 */
type MeasuredStrip = StripDepths & {
  /**
   * Глубина провала в каждом бине полосы.
   */
  depths: Float64Array;
};

/**
 * Глубина провала в одном бине: насколько он темнее медианы окна вокруг себя.
 * Медиана, а не среднее: узкий провал линии её не сдвигает, а горизонталь,
 * пересекающая полосу, меняется по столбцам медленнее окна и уходит в фон.
 *
 * @param values — профиль столбцов одной полосы
 * @param bin — бин полосы
 * @param window — ширина окна фона в бинах
 * @returns глубина провала в бине
 */
const measureStripDepth = (values: Float64Array, bin: number, window: number): number => {
  const half = Math.max(1, Math.floor(window / 2));
  const to = Math.min(values.length, bin + half + 1);
  const slice: number[] = [];

  for (let inner = Math.max(0, bin - half); inner < to; inner += 1) {
    slice.push(values[inner] || 0);
  }

  return computeMedian(slice) - (values[bin] || 0);
};

/**
 * Ширина окна фона в бинах профиля столбцов — шаг разлиновки: одна мера для
 * профиля во всю высоту, для глубин полос и для зоны у края полосы, где они
 * не определены.
 *
 * @param step — шаг разлиновки в пикселях
 * @returns ширина окна в бинах
 */
const toBackgroundWindow = (step: number): number => {
  return Math.max(3, Math.round(step));
};

/**
 * Стоит ли положение не ближе полуокна фона к обоим краям полосы.
 *
 * Ближе полуокна глубина не определена: окно скользящей медианы обрезано
 * краем полосы и почти целиком лежит по одну сторону от бина. Если там обрыв
 * бумаги — край вырезки, за которым уже тёмная обложка или стол, — медиана
 * берёт уровень бумаги, и ступень «бумага → обложка» читается провалом, хотя
 * по другую сторону от него бумаги нет. Такой кандидат — край листа, а не
 * черта: настоящая линия поля стоит от края полосы на несколько шагов.
 *
 * @param bin — положение в бинах полосы
 * @param size — число бинов полосы
 * @param halfWindow — полуширина окна фона в бинах
 * @returns `true` — глубина в этом положении мерилась полным окном
 */
const isInsideMeasuredBins = (bin: number, size: number, halfWindow: number): boolean => {
  return bin >= halfWindow && size - 1 - bin >= halfWindow;
};

/**
 * Глубины провалов во всех бинах полосы разом.
 *
 * @param strip — профиль столбцов одной полосы
 * @param window — ширина окна фона в бинах
 * @returns глубина провала в каждом бине полосы
 */
const measureStripDepths = (strip: ShearedProfile, window: number): Float64Array => {
  const { values } = strip;
  const background = computeMovingMedian(values, window);
  const depths = new Float64Array(values.length);

  for (let bin = 0; bin < values.length; bin += 1) {
    depths[bin] = (background[bin] || 0) - (values[bin] || 0);
  }

  return depths;
};

/**
 * Снимает глубины со всех полос разом — мера для полосового опроса.
 *
 * @param strips — профили столбцов по полосам
 * @param step — шаг разлиновки в пикселях
 * @returns полосы вместе с глубинами всех своих бинов
 */
const toStripDepths = (strips: ShearedProfile[], step: number): MeasuredStrip[] => {
  const window = toBackgroundWindow(step);

  return strips.map((strip) => {
    const depths = measureStripDepths(strip, window);

    return {
      depthAt: (bin: number): number => {
        return depths[bin] || 0;
      },
      depths,
      strip,
    };
  });
};

/**
 * Полосы с мерой глубины по требованию: бин считается при первом обращении и
 * запоминается. Мера для трассы — она опрашивает окна вокруг предсказаний, и
 * снятая наперёд полоса целиком ушла бы в мусор почти вся.
 *
 * @param strips — профили столбцов по полосам
 * @param step — шаг разлиновки в пикселях
 * @returns полосы с мерой глубины по требованию
 */
const toTracedStripDepths = (strips: ShearedProfile[], step: number): StripDepths[] => {
  const window = toBackgroundWindow(step);

  return strips.map((strip) => {
    const { values } = strip;
    const depths = new Float64Array(values.length);
    const isMeasured = new Uint8Array(values.length);

    return {
      depthAt: (bin: number): number => {
        if (bin < 0 || bin >= values.length) {
          return 0;
        }

        if (!isMeasured[bin]) {
          depths[bin] = measureStripDepth(values, bin, window);
          isMeasured[bin] = 1;
        }

        return depths[bin] || 0;
      },
      strip,
    };
  });
};

/**
 * Положение вертикальной линии в одной полосе.
 */
type TraceNode = {
  /**
   * Положение линии в пикселях фотографии.
   */
  position: number;

  /**
   * Глубина провала линии.
   */
  depth: number;
};

/**
 * Самый глубокий провал в окне вокруг предсказанного положения линии,
 * уточнённый по соседним бинам.
 *
 * @param band — полоса вместе с глубинами своих бинов
 * @param center — предсказанное положение линии в пикселях фотографии
 * @param reach — полуширина окна в пикселях
 * @returns положение и глубина провала; `null` — в окне нет ничего темнее фона
 */
const findStripDip = (
  band: StripDepths,
  center: number,
  reach: number
): TraceNode | null => {
  const { depthAt, strip } = band;
  const { origin, values } = strip;
  const from = Math.max(1, Math.round(center - reach) - origin);
  const to = Math.min(values.length - 2, Math.round(center + reach) - origin);
  let peak = -1;
  let depth = 0;

  for (let bin = from; bin <= to; bin += 1) {
    const binDepth = depthAt(bin);

    if (binDepth > depth) {
      peak = bin;
      depth = binDepth;
    }
  }

  if (peak < 0) {
    return null;
  }

  const offset = refinePeakOffset(depthAt(peak - 1), depth, depthAt(peak + 1));

  return { position: origin + peak + offset, depth };
};

/**
 * Прослеживает вертикальную линию по горизонтальным полосам кадра. Старт — в
 * полосе, где провал в окне `TRACE_START_SHARE` вокруг `center` глубже всего;
 * дальше вверх и вниз окно `LINE_SEARCH_SHARE` идёт за положением в последней
 * полосе, где линия нашлась. Полоса с провалом мельче `TRACE_DEPTH_SHARE`
 * стартового не голосует, и трасса идёт дальше от последнего узла: у спирали
 * и края листа линии может не быть, а на клетке в окно попадают обычные
 * вертикали.
 *
 * @param bands — полосы с глубинами своих бинов, сверху вниз
 * @param center — положение линии по профилю во всю высоту
 * @param step — шаг разлиновки в пикселях
 * @param minDepth — наименьшая глубина стартового узла
 * @param startCap — стартовый узел строго мельче этой глубины; без неё старт —
 *   самый глубокий провал
 * @returns узел линии в каждой полосе сверху вниз; `null` на месте полосы, где
 *   линия не нашлась, и во всех полосах — когда нет стартового узла
 */
const traceVerticalNodes = (
  bands: StripDepths[],
  center: number,
  step: number,
  minDepth: number,
  startCap = Number.POSITIVE_INFINITY
): (TraceNode | null)[] => {
  const starts = bands.map((band) => {
    return findStripDip(band, center, step * TRACE_START_SHARE);
  });
  const startIndex = starts.reduce((best, node, index) => {
    return node && node.depth < startCap && node.depth > (starts[best]?.depth || 0)
      ? index
      : best;
  }, -1);
  const start = starts[startIndex];
  const nodes = bands.map((): TraceNode | null => {
    return null;
  });

  if (!start || start.depth < minDepth) {
    return nodes;
  }

  const reach = step * LINE_SEARCH_SHARE;
  const threshold = start.depth * TRACE_DEPTH_SHARE;

  nodes[startIndex] = start;

  for (const direction of [-1, 1]) {
    let previous = start.position;

    for (
      let index = startIndex + direction;
      index >= 0 && index < bands.length;
      index += direction
    ) {
      const band = bands[index];
      const node = band ? findStripDip(band, previous, reach) : null;

      if (node && node.depth >= threshold) {
        nodes[index] = node;
        previous = node.position;
      }
    }
  }

  return nodes;
};

/**
 * Положения вертикальной линии по полосам: та же трасса, только без глубин.
 *
 * @param strips — профили столбцов по полосам, сверху вниз
 * @param center — положение линии по профилю во всю высоту
 * @param step — шаг разлиновки в пикселях
 * @param minDepth — наименьшая глубина стартового узла
 * @returns положения линии в полосах, где она нашлась, сверху вниз; пустой
 *   список — стартового узла нет
 */
const traceVerticalLine = (
  strips: ShearedProfile[],
  center: number,
  step: number,
  minDepth: number
): number[] => {
  return traceVerticalNodes(
    toTracedStripDepths(strips, step),
    center,
    step,
    minDepth
  ).reduce<number[]>((found, node) => {
    if (node) {
      found.push(node.position);
    }

    return found;
  }, []);
};

/**
 * Самое внутреннее положение границы по полосам. Перед выбором положение в
 * каждой полосе заменяется медианой по ней и двум соседним: узкая полоса
 * шумнее профиля во всю высоту, и одиночный выброс внутрь сузил бы блок на
 * всей странице. У крайней полосы недостающим соседом служит она сама.
 *
 * @param positions — положения границы по порядку полос
 * @param isLeftBorder — граница слева от области письма: самое внутреннее
 *   положение — наибольшее, иначе наименьшее
 * @returns самое внутреннее положение; `null` — ни одна полоса не голосовала
 */
const pickInnermost = (positions: number[], isLeftBorder: boolean): number | null => {
  if (positions.length === 0) {
    return null;
  }

  const last = positions.length - 1;
  const smoothed = positions.map((position, index) => {
    return computeMedian([
      positions[Math.max(0, index - 1)] || 0,
      position,
      positions[Math.min(last, index + 1)] || 0,
    ]);
  });

  return isLeftBorder ? Math.max(...smoothed) : Math.min(...smoothed);
};

/**
 * Полосы равной высоты, по высоте пересекающие область с линиями у столбца
 * `lineX`: строк над разлиновкой и под ней нет, и граница, изогнутая только
 * там, не должна сужать блок.
 *
 * @param count — число полос на кадр
 * @param height — высота кадра
 * @param span — область с линиями; `null` — не найдена, берутся все полосы
 * @param tangent — тангенс наклона разлиновки
 * @param lineX — столбец, у которого стоит прослеживаемая линия
 * @returns индексы полос, пересекающих область, полуинтервалом сверху вниз
 */
const toSpanStripRange = (
  count: number,
  height: number,
  span: RuledSpan | null,
  tangent: number,
  lineX: number
): StripRange => {
  if (!span || count === 0) {
    return [0, count];
  }

  const stripHeight = height / count;
  const from = Math.max(0, Math.floor((span.first + lineX * tangent) / stripHeight));
  const to = Math.min(count, Math.ceil((span.last + lineX * tangent) / stripHeight));

  return [from, Math.max(from + 1, to)];
};

/**
 * Уточняет линию поля трассировкой по полосам: берётся её самое внутреннее
 * положение, но не наружу от положения по профилю во всю высоту. Профиль во
 * всю высоту отдаёт среднее положение изогнутой линии, и блок, выложенный от
 * него, заходил бы за линию там, где она изогнута внутрь.
 *
 * @param marginLine — линия поля по профилю во всю высоту
 * @param strips — профили столбцов по полосам внутри области с линиями
 * @param step — шаг разлиновки в пикселях
 * @returns линия поля в самом внутреннем положении
 */
const refineMarginLine = (
  marginLine: MarginLine,
  strips: ShearedProfile[],
  step: number
): MarginLine => {
  const { x, side } = marginLine;
  const innermost = pickInnermost(
    traceVerticalLine(strips, x, step, MARGIN_LINE_MIN_DEPTH),
    side === 'left'
  );

  if (innermost === null) {
    return marginLine;
  }

  switch (side) {
    case 'left': {
      return { x: Math.max(x, innermost), side };
    }

    case 'right': {
      return { x: Math.min(x, innermost), side };
    }

    default: {
      throw new Error(`Неизвестная сторона линии поля: ${side}`);
    }
  }
};

/**
 * Итог полосового опроса линии поля: сам кандидат и числа, по которым его
 * приняли или отвергли.
 *
 * Числа идут наружу вместе с кандидатом, а не остаются внутри: барьер
 * складывается из трёх порогов, и без имени связавшего порога и отношения
 * глубин калибровка крутила бы число, которое на снимке ничего не решает.
 */
export type BandedMarginLine = {
  /**
   * Доля полос, в которых трасса нашла кандидата.
   */
  coverage: number;

  /**
   * Глубина кандидата — медиана по полосам, где трасса его нашла. Ноль —
   * кандидатов не нашлось вовсе.
   */
  depth: number;

  /**
   * Кандидат в том же виде, в каком линию поля отдаёт профиль во всю высоту;
   * `null` — барьер не взят или кандидатов нет.
   */
  line: MarginLine | null;

  /**
   * Отношение глубины кандидата к глубине соседей. Ноль — соседей не нашлось,
   * и кандидата держит не барьер по ним.
   */
  ratio: number;

  /**
   * Порог, из которого сложился барьер.
   */
  threshold: MarginLineThreshold;
};

const NO_BANDED_MARGIN_LINE: BandedMarginLine = {
  coverage: 0,
  depth: 0,
  line: null,
  ratio: 0,
  threshold: 'minimum',
};

/**
 * Пики глубины полосы внутри зоны бинов.
 *
 * Пик мельче `MARGIN_LINE_MIN_DEPTH` в список не попадает: барьер никогда не
 * бывает ниже этого этажа, а прослеживать зерно бумаги по всем полосам дорого.
 *
 * @param depths — глубины провалов полосы
 * @param origin — координата нулевого бина в пикселях фотографии
 * @param from — первый бин зоны
 * @param to — последний бин зоны
 * @returns пики зоны с уточнённым по соседним бинам положением
 */
const collectStripPeaks = (
  depths: Float64Array,
  origin: number,
  from: number,
  to: number
): TraceNode[] => {
  const peaks: TraceNode[] = [];
  const last = Math.min(depths.length - 2, to);

  for (let bin = Math.max(1, from); bin <= last; bin += 1) {
    const depth = depths[bin] || 0;

    if (!isDepthPeak(depths, bin) || depth < MARGIN_LINE_MIN_DEPTH) {
      continue;
    }

    const offset = refinePeakOffset(depths[bin - 1] || 0, depth, depths[bin + 1] || 0);

    peaks.push({ position: origin + bin + offset, depth });
  }

  return peaks;
};

/**
 * Пики соседних полос, слитые по месту: одна и та же линия даёт пик в каждой
 * полосе, и без слияния она прослеживалась бы трижды. Из пиков, стоящих ближе
 * окна трассы друг к другу, остаётся глубочайший — трасса всё равно свела бы
 * их в одну линию.
 *
 * @param peaks — пики нескольких полос
 * @param reach — полуширина окна трассы в пикселях
 * @returns пики без повторов, от глубокого к мелкому
 */
const mergeStripPeaks = (peaks: TraceNode[], reach: number): TraceNode[] => {
  const sorted = [...peaks].sort((first, second) => {
    return second.depth - first.depth;
  });

  return sorted.reduce<TraceNode[]>((kept, peak) => {
    const isSeparate = kept.every((other) => {
      return Math.abs(other.position - peak.position) > reach;
    });

    if (isSeparate) {
      kept.push(peak);
    }

    return kept;
  }, []);
};

/**
 * Кандидат в линию поля, оценённый по своей трассе.
 */
type BandedCandidate = {
  /**
   * Доля полос, где трасса нашла кандидата.
   */
  coverage: number;

  /**
   * Медиана глубины по полосам, где трасса его нашла.
   */
  depth: number;

  /**
   * Самое внутреннее положение по трассе.
   */
  x: number;

  /**
   * Узлы трассы по полосам сверху вниз; `null` — в полосе кандидат не нашёлся.
   */
  nodes: (TraceNode | null)[];
};

/**
 * Краснота кандидата по узлам его трассы.
 *
 * @param nodes — узлы трассы по полосам опроса сверху вниз
 * @returns краснота в уровнях; `null` — вето по цвету выключено: канала нет
 *   или снимок серый
 */
type RednessMeasure = (nodes: (TraceNode | null)[]) => number | null;

/**
 * Мера без цвета: изображение только с яркостью или вызов вне детектора.
 *
 * @returns `null` — вето по цвету выключено
 */
const measureNoRedness: RednessMeasure = () => {
  return null;
};

/**
 * Проходит ли кандидат вето по цвету.
 *
 * @param redness — краснота; `null` — вето выключено
 * @returns `true` — кандидат не отвергнут цветом
 */
const isRedEnough = (redness: number | null): boolean => {
  return redness === null || redness >= MARGIN_LINE_MIN_REDNESS;
};

/**
 * Узлы трассы, разобранные по величинам: глубины — для оценки кандидата,
 * положения — для выбора самого внутреннего из них.
 */
type TracedNodes = {
  /**
   * Глубины узлов по порядку найденных полос.
   */
  depths: number[];

  /**
   * Положения узлов по порядку найденных полос.
   */
  positions: number[];
};

/**
 * Ведёт кандидата трассой по всем полосам и оценивает его медианой глубины и
 * долей полос, где трасса его нашла.
 *
 * Медиана по трассе, а не среднее по полосам: линия под пятном, под текстом
 * или у края области пропадает в отдельных полосах, и среднее с нулями
 * повторило бы размывание профиля во всю высоту — то самое, ради снятия
 * которого полосовой опрос и заводится.
 *
 * @param bands — полосы с глубинами своих бинов, сверху вниз
 * @param center — положение кандидата в своей полосе
 * @param step — шаг разлиновки в пикселях
 * @param isLeftBorder — кандидат стоит слева от области письма
 * @param startCap — стартовый узел трассы строго мельче этой глубины
 * @returns оценка кандидата; `null` — трасса его не нашла ни в одной полосе
 */
const traceBandedCandidate = (
  bands: StripDepths[],
  center: number,
  step: number,
  isLeftBorder: boolean,
  startCap = Number.POSITIVE_INFINITY
): BandedCandidate | null => {
  const nodes = traceVerticalNodes(bands, center, step, MARGIN_LINE_MIN_DEPTH, startCap);
  const { depths, positions } = nodes.reduce<TracedNodes>(
    (found, node) => {
      if (node) {
        found.depths.push(node.depth);
        found.positions.push(node.position);
      }

      return found;
    },
    { depths: [], positions: [] }
  );
  const innermost = bands.length === 0 ? null : pickInnermost(positions, isLeftBorder);

  if (innermost === null) {
    return null;
  }

  return {
    coverage: positions.length / bands.length,
    depth: computeMedian(depths),
    x: innermost,
    nodes,
  };
};

/**
 * Ведёт кандидата в линию поля трассой и, если охвата `MARGIN_LINE_BAND_COVERAGE`
 * она не взяла, ведёт заново со старта мельче `TRACE_DEPTH_SHARE` прежнего —
 * пока охват не набран или старт не опустился ниже `MARGIN_LINE_MIN_DEPTH`.
 *
 * На сходящейся клетке черта пересекает вертикаль клетки, и на перекрёстке
 * глубины складываются: старт с него поднимает порог трассы выше собственной
 * глубины черты, и черта, идущая через все полосы, набирает один-два узла.
 * Повтор только для не взявшего охват: годный кандидат и соседи, из которых
 * складывается барьер, меряются одной трассой, как и без повтора. Порог
 * трассы от квантиля стартовых узлов снял бы перекрёсток и без повтора, но
 * сдвинул бы глубины соседей, а с ними барьер.
 *
 * @param bands — полосы с глубинами своих бинов, сверху вниз
 * @param center — положение кандидата в своей полосе
 * @param step — шаг разлиновки в пикселях
 * @param isLeftBorder — кандидат стоит слева от области письма
 * @returns оценка по последней трассе; `null` — первая трасса не нашла
 *   кандидата ни в одной полосе
 */
const traceMarginLineCandidate = (
  bands: StripDepths[],
  center: number,
  step: number,
  isLeftBorder: boolean
): BandedCandidate | null => {
  const startDepths = bands.map((band) => {
    return findStripDip(band, center, step * TRACE_START_SHARE)?.depth || 0;
  });
  let scored = traceBandedCandidate(bands, center, step, isLeftBorder);
  let startCap = Number.POSITIVE_INFINITY;

  while (scored !== null && scored.coverage < MARGIN_LINE_BAND_COVERAGE) {
    const cap = startCap;
    const startDepth = startDepths.reduce((deepest, depth) => {
      return depth < cap && depth > deepest ? depth : deepest;
    }, 0);

    startCap = startDepth * TRACE_DEPTH_SHARE;

    const retraced =
      startCap < MARGIN_LINE_MIN_DEPTH
        ? null
        : traceBandedCandidate(bands, center, step, isLeftBorder, startCap);

    if (retraced === null) {
      break;
    }

    scored = retraced;
  }

  return scored;
};

/**
 * Барьер глубины, с которого кандидат принимается за линию поля.
 */
type MarginLineBarrier = {
  /**
   * Порог, из которого сложился барьер.
   */
  threshold: MarginLineThreshold;

  /**
   * Глубина, с которой кандидат принимается.
   */
  value: number;
};

/**
 * Складывает барьер глубины линии поля из трёх порогов.
 *
 * @param peerDepth — глубина соседних вертикалей
 * @param sigma — разброс глубин полосы
 * @returns барьер и имя связавшего порога
 */
const toMarginLineBarrier = (peerDepth: number, sigma: number): MarginLineBarrier => {
  const peers = MARGIN_LINE_DEPTH_RATIO * peerDepth;
  const spread = MARGIN_LINE_SIGMA_FACTOR * sigma;
  const value = Math.max(peers, spread, MARGIN_LINE_MIN_DEPTH);

  switch (value) {
    case peers: {
      return { threshold: 'peers', value };
    }

    case spread: {
      return { threshold: 'sigma', value };
    }

    default: {
      return { threshold: 'minimum', value };
    }
  }
};

/**
 * Опрашивает полосы у одного края кадра.
 *
 * Кандидаты берутся из самой глубокой полосы и двух соседних с ней: список из
 * одной полосы задавало бы пятно или строка текста, а список со всех полос
 * разом стоил бы трассы каждому зерну бумаги. Соседи — те же пики средней
 * трети тех же полос: барьер и кандидат обязаны меряться одной мерой, иначе их
 * отношение сравнивает полосу с профилем во всю высоту и ничего не отделяет.
 *
 * Линией становится самый глубокий кандидат среди взявших барьер и вето по
 * цвету, а не самый глубокий вообще: нейтральная вертикаль глубже красной
 * черты не закрывает черту. Без цвета это тот же самый глубокий кандидат —
 * у более мелкого барьер ниже взять нельзя.
 *
 * @param bands — полосы в `MARGIN_LINE_BAND_STEPS` шага внутри области с
 *   линиями вместе с глубинами своих бинов
 * @param step — шаг разлиновки в пикселях
 * @param width — ширина кадра в пикселях
 * @param side — край, у которого идёт опрос
 * @param measureRedness — краснота кандидата по узлам трассы
 * @returns кандидат и числа, по которым он принят или отвергнут; без принятого —
 *   числа самого глубокого годного кандидата, ближе всех подошедшего к линии
 */
const pollMarginLineSide = (
  bands: MeasuredStrip[],
  step: number,
  width: number,
  side: MarginLineSide,
  measureRedness: RednessMeasure = measureNoRedness
): BandedMarginLine => {
  const first = bands[0]?.strip;
  const size = first?.values.length || 0;
  const origin = first?.origin || 0;
  const leftEnd = Math.ceil(width * MARGIN_LINE_SEARCH_FRACTION) - origin;
  const rightStart = Math.floor(width * (1 - MARGIN_LINE_SEARCH_FRACTION)) - origin;

  if (size < 8 || leftEnd < 2 || rightStart > size - 2) {
    return NO_BANDED_MARGIN_LINE;
  }

  const isLeft = side === 'left';
  const searchFrom = isLeft ? 1 : rightStart + 1;
  const searchTo = isLeft ? leftEnd - 1 : size - 2;
  const zonePeaks = bands.map(({ depths }) => {
    return collectStripPeaks(depths, origin, searchFrom, searchTo);
  });
  const zoneDepths = zonePeaks.map((peaks) => {
    return peaks.reduce((deepestPeak, peak) => {
      return Math.max(deepestPeak, peak.depth);
    }, 0);
  });
  const deepest = zoneDepths.reduce((best, depth, index) => {
    return depth > (zoneDepths[best] || 0) ? index : best;
  }, 0);
  const from = Math.max(0, deepest - 1);
  const to = Math.min(bands.length, deepest + 2);
  const reach = toLineReach(step);
  const candidates = mergeStripPeaks(zonePeaks.slice(from, to).flat(), reach);
  const peers = mergeStripPeaks(
    bands.slice(from, to).flatMap(({ depths }) => {
      return collectStripPeaks(depths, origin, leftEnd, rightStart);
    }),
    reach
  );
  const halfWindow = toBackgroundWindow(step) / 2;
  /**
   * Годные кандидаты от глубокого к мелкому; при равной глубине первым идёт
   * тот, кто раньше в списке, — сортировка устойчивая.
   */
  const eligible = candidates
    .reduce<BandedCandidate[]>((kept, candidate) => {
      const scored = traceMarginLineCandidate(bands, candidate.position, step, isLeft);

      if (
        scored !== null &&
        scored.coverage >= MARGIN_LINE_BAND_COVERAGE &&
        isInsideMeasuredBins(scored.x - origin, size, halfWindow)
      ) {
        kept.push(scored);
      }

      return kept;
    }, [])
    .sort((first, second) => {
      return second.depth - first.depth;
    });
  const best = eligible[0] || null;
  const peerDepths = peers.reduce<number[]>((depths, peer) => {
    const scored = traceBandedCandidate(bands, peer.position, step, isLeft);

    if (scored) {
      depths.push(scored.depth);
    }

    return depths;
  }, []);
  const deviations = bands.slice(from, to).reduce<number[]>((values, { depths }) => {
    for (let bin = 1; bin < size - 1; bin += 1) {
      values.push(Math.abs(depths[bin] || 0));
    }

    return values;
  }, []);
  const peerDepth = computeQuantile(peerDepths, MARGIN_LINE_PEER_QUANTILE);
  const { threshold, value } = toMarginLineBarrier(
    peerDepth,
    NORMAL_MAD_FACTOR * computeMedian(deviations)
  );
  const accepted =
    eligible.find((candidate) => {
      return candidate.depth >= value && isRedEnough(measureRedness(candidate.nodes));
    }) || null;
  const reported = accepted || best;
  const depth = reported?.depth || 0;

  return {
    coverage: reported?.coverage || 0,
    depth,
    line: accepted && { x: accepted.x, side },
    ratio: peerDepth > 0 ? depth / peerDepth : 0,
    threshold,
  };
};

/**
 * Ступень, которой досталась линия поля.
 *
 * @param profileLine — кандидат профиля во всю высоту; `null` — профиль черту
 *   не нашёл
 * @param marginLine — линия поля разлиновки; `null` — её нет
 * @returns имя ступени
 */
const toMarginLineStage = (
  profileLine: MarginLine | null,
  marginLine: MarginLine | null
): MarginLineStage => {
  if (marginLine === null) {
    return 'none';
  }

  return profileLine === null ? 'banded' : 'profile';
};

/**
 * Ищет линию поля полосовым опросом — там, где профиль во всю высоту её
 * размазал: на листе, снятом под углом или с изгибом бумаги, черта поля идёт
 * под своим наклоном и в профиле, усреднённом по всей высоте кадра, тонет
 * среди вертикалей клетки.
 *
 * Мера глубины здесь идёт вдоль самой линии: кандидат прослеживается по
 * полосам и оценивается медианой глубины своих узлов, а не провалом в столбце
 * кадра. Полосы поэтому и вдвое ниже трассировочных (`MARGIN_LINE_BAND_STEPS`):
 * в высокой полосе черта, уходящая в сторону, размазывается по столбцам, и её
 * глубина падает до глубины обычной вертикали.
 *
 * @param strips — профили столбцов по полосам в `MARGIN_LINE_BAND_STEPS` шага
 *   внутри области с линиями
 * @param step — шаг разлиновки в пикселях
 * @param width — ширина кадра в пикселях
 * @param side — край, которым ограничен поиск; не задан — оба
 * @returns кандидат и числа, по которым он принят или отвергнут
 */
export const findBandedMarginLine = (
  strips: ShearedProfile[],
  step: number,
  width: number,
  side?: MarginLineSide
): BandedMarginLine => {
  return pollMarginLine(toStripDepths(strips, step), step, width, side);
};

/**
 * Полосовой опрос по полосам с уже снятыми глубинами — одна мера на вторую
 * ступень и на вето первой.
 *
 * Глубины снимаются снаружи, а не здесь: полоса у сторон и у вето общая, а
 * скользящая медиана по ней — самая дорогая часть опроса.
 *
 * @param bands — полосы опроса вместе с глубинами своих бинов
 * @param step — шаг разлиновки в пикселях
 * @param width — ширина кадра в пикселях
 * @param side — край, которым ограничен поиск; не задан — оба
 * @param measureRedness — краснота кандидата по узлам трассы
 * @returns кандидат и числа, по которым он принят или отвергнут
 */
const pollMarginLine = (
  bands: MeasuredStrip[],
  step: number,
  width: number,
  side?: MarginLineSide,
  measureRedness: RednessMeasure = measureNoRedness
): BandedMarginLine => {
  if (side !== undefined) {
    return pollMarginLineSide(bands, step, width, side, measureRedness);
  }

  const left = pollMarginLineSide(bands, step, width, 'left', measureRedness);
  const right = pollMarginLineSide(bands, step, width, 'right', measureRedness);

  /**
   * Глубины сравниваются только между сторонами, у которых кандидат взял
   * барьер и вето по цвету: барьер у каждой стороны свой — соседи и разброс берутся у её самой
   * глубокой полосы, — и более глубокий кандидат под своим барьером закрыл бы
   * линию, принятую у другой стороны.
   *
   * Не взяла барьер ни одна — отдаются числа более глубокой: линии нет, а
   * диагностике нужен кандидат, ближе всех подошедший к барьеру.
   */
  if ((left.line === null) !== (right.line === null)) {
    return left.line === null ? right : left;
  }

  return left.depth >= right.depth ? left : right;
};

/**
 * Решение вето по его двум мерам. Краснота решает только о кандидате, чью
 * сторону подтвердила яркость: у отвергнутого стороной она не мерится.
 *
 * @param isSideAccepted — полосовая мера подтвердила сторону кандидата
 * @param redness — краснота кандидата; `null` — вето по цвету выключено или
 *   краснота не мерилась
 * @returns решение вето
 */
const toMarginLineVerdict = (
  isSideAccepted: boolean,
  redness: number | null
): MarginLineVerdict => {
  if (!isSideAccepted) {
    return 'side';
  }

  return isRedEnough(redness) ? 'accepted' : 'colour';
};

/**
 * Проверяет кандидата профиля во всю высоту той же полосовой мерой, что ищет
 * вторая ступень, — трассой, медианой, охватом и барьером у его стороны.
 *
 * Профиль во всю высоту сравнивает кандидата с децилью средней трети, а не с
 * соседями вдоль линии: на листе со схождением клетки вертикали одной глубины
 * размываются в профиле по-разному, и резкая вертикаль у границы трети берёт
 * барьер по размытым. Вдоль линии она мельче соседей, настоящая черта — глубже.
 *
 * Подтверждается сторона, а не положение: у черты, идущей не параллельно
 * разлиновке, пик профиля — её среднее положение, и полосы находят её в трети
 * шага и дальше от него. Поэтому `x` принятого кандидата остаётся от профиля
 * до бита, а сверки положения, кроме правила края полосы, нет. Правило края
 * берётся на самом кандидате: у края вырезки провал в профиле даёт обрыв
 * бумаги или тень, и сторона, подтверждённая настоящей чертой дальше от края,
 * не делает его линией поля.
 *
 * Сторона подтверждается одной яркостью, а краснота мерится на самом
 * кандидате — по трассе от его положения в профиле: красная черта у той же
 * стороны не делает линией поля нейтральную вертикаль, на которую указал
 * профиль.
 *
 * @param candidate — линия поля по профилю во всю высоту
 * @param bands — полосы опроса вместе с глубинами своих бинов
 * @param step — шаг разлиновки в пикселях
 * @param width — ширина кадра в пикселях
 * @param measureRedness — краснота по узлам трассы
 * @returns решение и числа полосовой меры у стороны кандидата
 */
const vetoMarginLine = (
  candidate: MarginLine,
  bands: MeasuredStrip[],
  step: number,
  width: number,
  measureRedness: RednessMeasure
): MarginLineVeto => {
  const first = bands[0]?.strip;
  const polled = pollMarginLineSide(bands, step, width, candidate.side);
  const isMeasured =
    first !== undefined &&
    isInsideMeasuredBins(
      candidate.x - first.origin,
      first.values.length,
      toBackgroundWindow(step) / 2
    );
  const isSideAccepted = polled.line !== null && isMeasured;
  const redness = isSideAccepted
    ? measureRedness(traceVerticalNodes(bands, candidate.x, step, MARGIN_LINE_MIN_DEPTH))
    : null;

  return {
    verdict: toMarginLineVerdict(isSideAccepted, redness),
    side: candidate.side,
    coverage: polled.coverage,
    ratio: polled.ratio,
    threshold: polled.threshold,
    redness,
  };
};

/**
 * Боковые границы области с горизонтальными линиями в пикселях фотографии.
 */
type RowBorders = {
  /**
   * Левая граница; 0 — линии доходят до левого края.
   */
  left: number;

  /**
   * Правая граница; ширина кадра — линии доходят до правого края.
   */
  right: number;
};

const computePooledQuantile = (profiles: Float64Array[], quantile: number): number => {
  const total = profiles.reduce((sum, values) => {
    return sum + values.length;
  }, 0);
  const pooled = new Float64Array(total);
  let offset = 0;

  for (const values of profiles) {
    pooled.set(values, offset);
    offset += values.length;
  }

  pooled.sort();

  return pooled[Math.min(total - 1, Math.floor(total * quantile))] || 0;
};

/**
 * Есть ли на отрезке `[from, to)` ряда участок не короче `length` отсчётов
 * подряд с уровнем не ниже `threshold`.
 */
const hasSignalRun = (
  values: Float64Array,
  from: number,
  to: number,
  threshold: number,
  length: number
): boolean => {
  let run = 0;

  for (let index = from; index < to; index += 1) {
    run = (values[index] || 0) >= threshold ? run + 1 : 0;

    if (run >= length) {
      return true;
    }
  }

  return false;
};

/**
 * Уточняет боковые границы области с линиями по полосам вдоль линий высотой
 * `LINE_END_BAND_STEPS` (`buildBandCombResponses`): граница берётся в каждой
 * полосе, итог — самая внутренняя, но не наружу от границы по отклику во всю
 * высоту. Отклик во всю высоту усредняет концы линий, и у линий, кончающихся на
 * разном отступе, граница выходит между крайними концами.
 *
 * Обрыв в полосе голосует, только если за ним нет участка длиной в шаг с
 * откликом не ниже половины девятой децили, общей для всех полос: бледное
 * пятно на нескольких соседних полосах рвёт отклик каждой из них, и медиана по
 * трём полосам его не снимает, но за пятном линии продолжаются. Участок короче
 * шага — пятно спирали или ступень яркости у края стола — голосу не мешает.
 *
 * Полосы берутся только внутри области с линиями по высоте: над разлиновкой и
 * под ней отклика нет, и там обрыв вышел бы на всю ширину. Сторона, где отклик
 * во всю высоту дошёл до края профиля, тоже уточняется: защитная полоса
 * наклона во всю высоту кадра шире, чем у полосы, и прячет концы у края кадра.
 *
 * @param image — полутоновая выжимка
 * @param skewAngle — наклон разлиновки в градусах
 * @param period — шаг и фаза горизонтальных линий
 * @param span — область с линиями по высоте
 * @param borders — границы по отклику во всю высоту
 * @returns уточнённые границы
 */
const refineRowBorders = (
  image: SheetImageData,
  skewAngle: number,
  period: ProfilePeriod,
  span: RuledSpan | null,
  borders: RowBorders
): RowBorders => {
  const { step, phase } = period;

  if (!span) {
    return borders;
  }

  const firstLine = Math.round((span.first - phase) / step);
  const lastLine = Math.round((span.last - phase) / step);
  const bandCount = Math.floor((lastLine - firstLine + 1) / LINE_END_BAND_STEPS);

  if (bandCount < 1) {
    return borders;
  }

  /**
   * Границы полос — посередине между линиями: изгиб до трёх десятых шага их не
   * пересекает. Остаток линий, не набравший полосы, уходит в последнюю.
   */
  const alongEdges = Array.from({ length: bandCount + 1 }, (_item, band) => {
    const line =
      band === bandCount ? lastLine + 1 : firstLine + band * LINE_END_BAND_STEPS;

    return phase + (line - 0.5) * step;
  });
  const window = Math.max(1, Math.round(step));
  const bands = buildBandCombResponses(image, skewAngle, step, phase, alongEdges).map(
    ({ values, origin }) => {
      return { values: closeProfileGaps(values, window), origin };
    }
  );
  const threshold =
    RULING_REGION_LEVEL *
    computePooledQuantile(
      bands.map(({ values }) => {
        return values;
      }),
      0.9
    );
  const leftVotes: number[] = [];
  const rightVotes: number[] = [];

  for (const { values, origin } of bands) {
    const region = findSignalRegion(values, RULING_REGION_LEVEL);

    if (
      region &&
      region.start > 0 &&
      !hasSignalRun(values, 0, region.start, threshold, window)
    ) {
      leftVotes.push(origin + region.start);
    }

    if (
      region &&
      region.end < values.length - 1 &&
      !hasSignalRun(values, region.end + 1, values.length, threshold, window)
    ) {
      rightVotes.push(origin + region.end + 1);
    }
  }

  const left = pickInnermost(leftVotes, true);
  const right = pickInnermost(rightVotes, false);

  return {
    left: left === null ? borders.left : Math.max(borders.left, left),
    right: right === null ? borders.right : Math.min(borders.right, right),
  };
};

/**
 * Ищет крайние вертикальные линии клетки.
 *
 * Шаг берётся у горизонтальных линий, а фаза подбирается перебором: клетка
 * квадратная, а автокорреляцию столбцов на снимке тетради сбивают край листа и
 * спираль — периода там не находится вовсе.
 *
 * Вертикали прослеживаются вдоль самих линий по полосам (`traceCombDepths`), и
 * область с вертикалями ищется по их трассе: на снимке телефоном вертикали
 * расходятся книзу и изогнуты, у края области прямая гребёнка проходит мимо
 * крайней линии в части полос, и граница уходила бы на линию внутрь. Крайняя
 * линия берётся в самом внутреннем положении по полосам, пересекающим область с
 * горизонтальными линиями, но не дальше окна `LINE_SEARCH_SHARE` наружу от
 * прямой гребёнки: граница по гребёнке у одного из краёв листа легла бы за
 * линию.
 *
 * @param strips — профили столбцов по горизонтальным полосам кадра
 * @param step — шаг горизонтальных линий в пикселях
 * @param rowDepth — типичная глубина горизонтальной линии
 * @param selectSpanRange — полосы, пересекающие область с горизонтальными
 *   линиями у заданного столбца, полуинтервалом индексов
 * @returns крайние вертикальные линии; `null` — вертикальных линий клетки нет
 */
const findGridColumns = (
  strips: ShearedProfile[],
  step: number,
  rowDepth: number,
  selectSpanRange: (lineX: number) => StripRange
): GridColumns | null => {
  const origin = strips[0]?.origin || 0;
  const detrendedStrips = detrendStrips(strips, step);
  let bestPhase = 0;
  let bestScore = 0;

  for (let phase = 0; phase < step; phase += 1) {
    const score = computeMedian(
      measureCombDepths(detrendedStrips, origin, step, phase).depths
    );

    if (score > bestScore) {
      bestPhase = phase;
      bestScore = score;
    }
  }

  if (bestScore <= 0 || bestScore < rowDepth * GRID_COLUMN_LEVEL) {
    return null;
  }

  const { positions, depths, stripPositions, measurable } = traceCombDepths(
    detrendedStrips,
    origin,
    step,
    bestPhase
  );
  const region = findSignalRegion(Float64Array.from(depths), RULED_SPAN_LEVEL);

  if (!region) {
    return null;
  }

  const firstLine = positions[region.start] || 0;
  const lastLine = positions[region.end] || 0;
  const hasLeft = region.start > Math.max(0, measurable.indexOf(true));
  const hasRight = region.end < measurable.lastIndexOf(true);

  const pickColumn = (
    index: number,
    lineX: number,
    isLeftBorder: boolean
  ): number | null => {
    const [from, to] = selectSpanRange(lineX);
    const found = (stripPositions[index] || []).reduce<number[]>(
      (acc, position, strip) => {
        if (position !== null && strip >= from && strip < to) {
          acc.push(position);
        }

        return acc;
      },
      []
    );

    return pickInnermost(found, isLeftBorder);
  };

  /**
   * Наружу граница уходит от прямой гребёнки не дальше, чем линия ещё считается
   * своей гребёнке: на снимках клетки пресет-пака крайняя вертикаль стоит на
   * четыре пикселя дальше гребёнки, и граница по самой гребёнке сузила бы блок.
   */
  const reach = toLineReach(step);
  const innermostLeft = hasLeft && pickColumn(region.start, firstLine, true);
  const innermostRight = hasRight && pickColumn(region.end, lastLine, false);

  return {
    left: hasLeft
      ? Math.max(firstLine - reach, innermostLeft || firstLine - reach)
      : null,
    right: hasRight
      ? Math.min(lastLine + reach, innermostRight || lastLine + reach)
      : null,
  };
};

/**
 * Границы области с линиями — самая длинная непрерывная цепочка линий гребёнки,
 * которые действительно темнее фона. Опрос по гребёнке, а не поиск провалов
 * подряд: шаг и фаза уже известны, и по ним видно не только где линии есть, но
 * и где их не стало.
 *
 * @param comb — линии гребёнки с глубинами
 * @returns координаты первой и последней линии, упёрлась ли цепочка в край
 *   профиля, и типичная глубина линии; `null` — линий меньше трёх
 */
const toRuledSpan = (comb: TracedComb): RuledSpan | null => {
  const { positions, depths, stripPositions, measurable } = comb;

  if (depths.length < 3) {
    return null;
  }

  const sorted = [...depths].sort((left, right) => {
    return left - right;
  });
  const reference = sorted[Math.floor(sorted.length * 0.9)] || 0;

  if (reference <= 0) {
    return null;
  }

  const threshold = reference * RULED_SPAN_LEVEL;
  let bestStart = -1;
  let bestEnd = -1;
  let runStart = -1;

  for (let index = 0; index <= depths.length; index += 1) {
    const isInside = index < depths.length && (depths[index] || 0) >= threshold;

    if (isInside && runStart < 0) {
      runStart = index;
    }

    if (!isInside && runStart >= 0) {
      if (index - runStart > bestEnd - bestStart) {
        bestStart = runStart;
        bestEnd = index - 1;
      }

      runStart = -1;
    }
  }

  if (bestStart < 0) {
    return null;
  }

  return {
    first: positions[bestStart] || 0,
    last: positions[bestEnd] || 0,
    isAtProfileStart: bestStart <= Math.max(0, measurable.indexOf(true)),
    isAtProfileEnd: bestEnd >= measurable.lastIndexOf(true),
    depth: reference,
    firstStrips: stripPositions[bestStart] || [],
    lastStrips: stripPositions[bestEnd] || [],
  };
};

/**
 * Границы области с линиями по трассе вдоль линий (`traceCombDepths`): у края
 * листа линии уходят от прямой гребёнки на волне бумаги больше чем на окно
 * опроса, и цепочка по прямой гребёнке обрывалась бы на линию-другую раньше.
 *
 * @param strips — профили средней яркости по полосам кадра с общими бинами
 * @param step — шаг разлиновки в пикселях
 * @param phase — смещение линий по модулю шага
 * @returns область с линиями; `null` — линий меньше трёх
 */
const findRuledSpan = (
  strips: ShearedProfile[],
  step: number,
  phase: number
): RuledSpan | null => {
  return toRuledSpan(
    traceCombDepths(detrendStrips(strips, step), strips[0]?.origin || 0, step, phase)
  );
};

/**
 * Ядро области с линиями — цепочка линий, подтверждённых опросом в окне
 * `LINE_SEARCH_SHARE` у прямой гребёнки. Край профиля у неё — первая и
 * последняя линии, попавшие в профиль.
 *
 * @param strips — профили средней яркости по полосам кадра с общими бинами
 * @param step — шаг разлиновки в пикселях
 * @param phase — смещение линий по модулю шага
 * @returns ядро области; `null` — линий меньше трёх
 */
const findRuledCore = (
  strips: ShearedProfile[],
  step: number,
  phase: number
): RuledSpan | null => {
  const comb = measureCombDepths(
    detrendStrips(strips, step),
    strips[0]?.origin || 0,
    step,
    phase
  );

  return toRuledSpan({
    ...comb,
    stripPositions: [],
    measurable: comb.depths.map(() => {
      return true;
    }),
  });
};

const isSameStep = (first: number, second: number): boolean => {
  if (first <= 0 || second <= 0) {
    return false;
  }

  return Math.abs(first - second) / first <= GRID_STEP_TOLERANCE;
};

/**
 * Область измерения изгиба в столбцах кадра: от концов горизонтальных линий,
 * а со стороны линии поля — до неё. Концы и линия поля найдены вдоль
 * вертикалей разлиновки, а полосы изгиба режутся по столбцам кадра: на
 * наклонном листе граница проходит кадр наискосок, и область берётся по её
 * самому внутреннему положению между верхней и нижней линиями. Иначе крайняя
 * полоса на части строк легла бы за концы линий или за линию поля, где трасса
 * цепляется за пятна спирали и чужую линейку.
 *
 * @param image — полутоновая выжимка
 * @param tangent — тангенс наклона разлиновки
 * @param margins — найденные поля: по верхнему и нижнему видно высоту области
 * @param rowBorders — концы горизонтальных линий
 * @param marginLine — линия поля; `null` — её нет
 * @returns горизонтальная область с линиями
 */
const toBendRegion = (
  image: SheetImageData,
  tangent: number,
  margins: PaperMargins,
  rowBorders: RowBorders,
  marginLine: MarginLine | null
): RulingBendRegion => {
  const topShift = margins.top * tangent;
  const bottomShift = (image.height - margins.bottom) * tangent;
  const leftShift = Math.min(topShift, bottomShift);
  const rightShift = Math.max(topShift, bottomShift);
  const left = rowBorders.left > 0 ? rowBorders.left - leftShift : 0;
  const right =
    rowBorders.right < image.width ? rowBorders.right - rightShift : image.width;

  if (!marginLine) {
    return { left, right };
  }

  switch (marginLine.side) {
    case 'left': {
      return { left: Math.max(left, marginLine.x - leftShift), right };
    }

    case 'right': {
      return { left, right: Math.min(right, marginLine.x - rightShift) };
    }

    default: {
      throw new Error(`Неизвестная сторона линии поля: ${marginLine.side}`);
    }
  }
};

/**
 * Настройки замера периода разлиновки: те же, что у поиска разлиновки, но уже
 * с подставленными значениями по умолчанию.
 */
type RulingPeriodOptions = Required<
  Pick<
    RulingDetectionOptions,
    | 'minStep'
    | 'maxStepFraction'
    | 'confidenceThreshold'
    | 'maxAngle'
    | 'angleStep'
    | 'maxAnalysisSize'
  >
> &
  Pick<RulingDetectionOptions, 'skewAngle'>;

/**
 * Период разлиновки вместе с наклоном, на котором он измерен, и числами
 * полосовой ступени.
 */
type RulingPeriodStage = {
  /**
   * Период найден. `false` — обе ступени отказали.
   */
  isDetected: boolean;

  /**
   * Наклон в градусах, на котором измерены шаг и фаза.
   */
  skewAngle: number;

  /**
   * Шаг, фаза и уверенность. Уверенность всегда от глобального профиля: по ней
   * и видно, какая из ступеней дала шаг.
   */
  period: ProfilePeriod;

  /**
   * Что сделала полосовая ступень: не понадобилась, отказала или дала шаг.
   */
  bandedStage: RulingBandedStage;

  /**
   * Шаги полос кадра сверху вниз; пусто у любой ступени, кроме `measured`.
   */
  bandSteps: number[];

  /**
   * Засев схождения полосовой ступени, 1/px.
   */
  convergenceSeed: number;

  /**
   * Начало отсчёта координаты вдоль линий для шага и засева.
   */
  convergenceOrigin: number;
};

/**
 * Меряет период разлиновки двумя ступенями. Первая — профиль яркости по всему
 * кадру: пока он берёт порог уверенности, вторая не считается вовсе, и числа
 * ровного листа остаются прежними до бита.
 *
 * Вторая ступень — полосы поперёк линий (`measureBandedPeriod`). Она нужна
 * листу, у которого равномерной гребёнки на весь кадр не существует: шаг по
 * кадру плывёт, общий профиль размывается и порога не берёт, а внутри полосы
 * дрейфу накопиться негде.
 *
 * Наклон полосовая ступень приносит свой: на кадре фотографии другого источника
 * наклона нет, а фаза отсчитана в координате вдоль линий и с чужим углом
 * указывает мимо них. Поэтому шаг, фаза и наклон уходят наружу одной тройкой.
 *
 * Заданный настройками наклон ступень не переопределяет. Его задают
 * изображению, наклон которого известен по построению, — выпрямленной копии, у
 * которой линии лежат ровно под ним. Свип полосы там ничего не уточняет: он
 * меряет резкость всего, что в полосу попало, вместе с пружиной, переплётом и
 * поверхностью за краем листа, и его угол — компромисс между ними. Отдай
 * ступень наружу этот угол, и поля с линией поля встали бы в координату вдоль
 * линий, которой у копии нет, а вызывающая сторона отбросила бы весь проход
 * как непарный.
 *
 * @param image — полутоновая выжимка фотографии листа
 * @param skewAngle — наклон в градусах для глобального профиля
 * @param options — настройки замера
 * @returns период вместе с наклоном, на котором он измерен, и числами полос
 */
const measureRulingPeriod = (
  image: SheetImageData,
  skewAngle: number,
  options: RulingPeriodOptions
): RulingPeriodStage => {
  const {
    minStep,
    maxStepFraction,
    confidenceThreshold,
    maxAngle,
    angleStep,
    maxAnalysisSize,
  } = options;
  const rows = buildShearedProfile(image, 'horizontal', skewAngle, Math.abs(skewAngle));
  const maxStep = rows.values.length * maxStepFraction;
  const period = measureProfilePeriod(rows, minStep, maxStep);
  const flat: RulingPeriodStage = {
    isDetected: period.step > 0 && period.confidence >= confidenceThreshold,
    skewAngle,
    period,
    bandedStage: 'skipped',
    bandSteps: [],
    convergenceSeed: 0,
    convergenceOrigin: 0,
  };

  if (flat.isDetected) {
    return flat;
  }

  const banded = measureBandedPeriod(image, {
    minStep,
    maxStep,
    confidenceThreshold,
    maxAngle,
    angleStep,
    maxAnalysisSize,
  });

  if (banded.step <= 0) {
    return { ...flat, bandedStage: 'rejected' };
  }

  /**
   * Заданный наклон сохраняется: нулевой — валидное измерение, а не «значения
   * нет», и `||` подменил бы ровный лист наклоном полос.
   */
  return {
    isDetected: true,
    skewAngle: options.skewAngle ?? banded.skewAngle,
    period: { step: banded.step, phase: banded.phase, confidence: period.confidence },
    bandedStage: 'measured',
    bandSteps: banded.bandSteps,
    convergenceSeed: banded.convergence,
    convergenceOrigin: banded.origin,
  };
};

/**
 * Измеряет разлиновку на фотографии листа: шаг — автокорреляцией профиля
 * яркости, снятого вдоль наклонных линий, фазу и поля — по тому же профилю,
 * вид разлиновки — повторным измерением поперёк.
 *
 * Все длины — в пикселях переданного изображения: анализ идёт по нему, а не по
 * уменьшенной копии, поэтому шаг не нужно домножать на масштаб. Уменьшенная
 * копия используется только для свипа наклона, где масштаб роли не играет.
 *
 * Шаг ищется двумя ступенями (`measureRulingPeriod`): профилем по всему кадру,
 * а когда тот не берёт порог уверенности — полосами поперёк линий. Уверенность
 * в итоге всегда от профиля по кадру, поэтому у листа, шаг которого нашли
 * полосы, она ниже порога: разлиновка найдена, а ступень видна по непустым
 * `bandSteps`.
 *
 * Неудача не означает брак фотографии: `isDetected: false` включает ручной
 * ввод разлиновки, сама фотография остаётся годной.
 *
 * @param image — полутоновая выжимка фотографии листа
 * @param options — настройки поиска
 * @returns измеренная разлиновка вместе с наклоном и уверенностью
 */
export const detectRuling = (
  image: SheetImageData,
  options: RulingDetectionOptions = {}
): DetectedRuling => {
  const {
    maxAngle = MAX_SKEW_ANGLE,
    angleStep = SKEW_ANGLE_STEP,
    minStep = MIN_RULING_STEP,
    maxStepFraction = MAX_RULING_STEP_FRACTION,
    confidenceThreshold = RULING_CONFIDENCE_THRESHOLD,
    maxAnalysisSize = ANALYSIS_IMAGE_SIZE,
  } = options;
  /**
   * Нулевой наклон — валидное измерение, а не «значения нет»: `||` погнал бы
   * ровный лист на повторный свип.
   */
  const sweptAngle =
    options.skewAngle ?? detectSkewAngle(image, { maxAngle, angleStep, maxAnalysisSize });
  const stage = measureRulingPeriod(image, sweptAngle, {
    minStep,
    maxStepFraction,
    confidenceThreshold,
    maxAngle,
    angleStep,
    maxAnalysisSize,
    ...(options.skewAngle === undefined ? {} : { skewAngle: options.skewAngle }),
  });
  const {
    period,
    bandedStage,
    bandSteps,
    convergenceSeed,
    convergenceOrigin,
    skewAngle,
  } = stage;

  if (!stage.isDetected) {
    return toMissingDetection(period.confidence, skewAngle, bandedStage);
  }

  const guardAngle = Math.abs(skewAngle);

  const { columns, response: columnResponse } = buildColumnProfiles(
    image,
    skewAngle,
    guardAngle,
    period.step,
    period.phase
  );
  const columnPeriod: ProfilePeriod = measureProfilePeriod(
    columns,
    minStep,
    columns.values.length * maxStepFraction
  );
  const isGrid =
    columnPeriod.confidence >= confidenceThreshold &&
    isSameStep(period.step, columnPeriod.step);
  const spanStrips = buildStripProfiles(
    image,
    'horizontal',
    skewAngle,
    guardAngle,
    RULED_SPAN_STRIPS
  );
  const ruledSpan = findRuledSpan(spanStrips, period.step, period.phase);
  const ruledCore = findRuledCore(spanStrips, period.step, period.phase);
  const tangent = toTangent(skewAngle);
  /**
   * Полосы трассировки строятся лишь раз и лишь тогда, когда есть что
   * прослеживать: на линейке без линии поля проход по кадру не нужен.
   */
  let traceStrips: ShearedProfile[] | null = null;

  const selectTraceStrips = (lineX: number): ShearedProfile[] => {
    traceStrips =
      traceStrips ||
      buildStripProfiles(
        image,
        'vertical',
        skewAngle,
        guardAngle,
        Math.max(
          MIN_TRACE_STRIPS,
          Math.round(image.height / (TRACE_STRIP_STEPS * period.step))
        )
      );

    const [from, to] = toSpanStripRange(
      traceStrips.length,
      image.height,
      ruledSpan,
      tangent,
      lineX
    );

    return traceStrips.slice(from, to);
  };

  const gridColumns =
    ruledSpan &&
    findGridColumns(
      buildStripProfiles(image, 'vertical', skewAngle, guardAngle, RULED_SPAN_STRIPS),
      period.step,
      ruledSpan.depth,
      (lineX) => {
        return toSpanStripRange(
          RULED_SPAN_STRIPS,
          image.height,
          ruledSpan,
          tangent,
          lineX
        );
      }
    );
  const columnRegion = findSignalRegion(
    closeProfileGaps(columnResponse.values, Math.round(period.step)),
    RULING_REGION_LEVEL
  );

  /**
   * Полосы опроса строятся лишь тогда, когда линию поля вообще ищут, и один
   * раз на вето и на вторую ступень: при `marginLineSide: null` лишнего прохода
   * по пикселям не случается.
   *
   * Область с линиями режется у середины кадра, а не у самого кандидата:
   * кандидата до опроса ещё нет, а сдвиг среза на `lineX * tangent` внутри
   * трети поиска не дотягивает и до одной полосы. Зато кандидат и соседи
   * меряются по одним и тем же полосам — иначе их отношение сравнивало бы
   * разные меры.
   */
  const pollStripCount = Math.max(
    MIN_TRACE_STRIPS,
    Math.round(image.height / (MARGIN_LINE_BAND_STEPS * period.step))
  );

  const toPollRange = (stripCount: number): [number, number] => {
    return toSpanStripRange(
      stripCount,
      image.height,
      ruledSpan,
      tangent,
      image.width / 2
    );
  };

  const selectPollStrips = (): ShearedProfile[] => {
    const strips = buildStripProfiles(
      image,
      'vertical',
      skewAngle,
      guardAngle,
      pollStripCount
    );
    const [from, to] = toPollRange(strips.length);

    return strips.slice(from, to);
  };

  let pollBands: MeasuredStrip[] | null = null;

  const selectPollBands = (): MeasuredStrip[] => {
    pollBands = pollBands || toStripDepths(selectPollStrips(), period.step);

    return pollBands;
  };

  /**
   * Гейт и полосы красноты считаются лишь тогда, когда цвет что-то решает:
   * гейт — как только кандидат взял яркостные меры, полосы — вдобавок только
   * на цветном снимке и только в бинах у узлов кандидата. Серый снимок и
   * изображение без канала полос красноты не строят. Гейт, так и не
   * понадобившийся, уходит в отчёт пустым.
   */
  let colourGate: ColourGate | null = null;

  const selectColourGate = (): ColourGate => {
    /**
     * Без канала у самого входа красноту мерить не по чему: гейт выключен, как
     * бы ни был окрашен кадр, иначе вето отвергло бы любого кандидата.
     */
    if (colourGate === null && !image.redMinusGreen) {
      colourGate = { isEnabled: false, redGreenP99: null };
    }

    if (colourGate === null) {
      const redGreenP99 = options.measureFrameRedGreenP99
        ? options.measureFrameRedGreenP99()
        : measureRedGreenP99(image);

      colourGate = { isEnabled: isColourVetoEnabled(redGreenP99), redGreenP99 };
    }

    return colourGate;
  };

  let rednessStrips: RednessStrips | null = null;

  const selectRednessStrips = (): RednessStrips => {
    if (rednessStrips === null) {
      const built =
        buildRednessStrips(
          image,
          skewAngle,
          guardAngle,
          pollStripCount,
          toBackgroundWindow(period.step)
        ) || NO_REDNESS_STRIPS;
      const [from, to] = toPollRange(built.count);

      rednessStrips = sliceRednessStrips(built, from, to);
    }

    return rednessStrips;
  };

  const measureRedness: RednessMeasure = (nodes) => {
    return selectColourGate().isEnabled
      ? measureCandidateRedness(nodes, selectRednessStrips())
      : null;
  };

  const profileCandidate =
    options.marginLineSide === null
      ? null
      : findMarginLine(columns, period.step, image.width, options.marginLineSide);
  /**
   * Кандидат профиля во всю высоту становится линией поля, только пройдя вето
   * полосовой меры и вето по цвету, — на обоих проходах: гейт копии задаёт
   * сторону, но не отменяет проверку. Вето стоит до уточнения трассой и до
   * области изгиба: отвергнутая линия не успевает ни сдвинуться, ни обрезать
   * сетку.
   */
  const veto =
    profileCandidate &&
    vetoMarginLine(
      profileCandidate,
      selectPollBands(),
      period.step,
      image.width,
      measureRedness
    );
  const meanMarginLine = veto && veto.verdict === 'accepted' ? profileCandidate : null;
  /**
   * Полосовая ступень — вторая и только вторая: подтверждённый кандидат
   * профиля отдаёт своё число сам, и на листе, где он есть, полосы положение
   * не решают. Отвергнутый вето кандидат линии не даёт, и полосы ищут у тех
   * же краёв, что и профиль. Гейт `marginLineSide` держит обе ступени разом:
   * проход по выпрямленной копии не заводит линию, которой не нашёл проход по
   * кадру.
   */
  const banded =
    meanMarginLine === null && options.marginLineSide !== null
      ? pollMarginLine(
          selectPollBands(),
          period.step,
          image.width,
          options.marginLineSide,
          measureRedness
        )
      : null;
  const foundMarginLine = meanMarginLine || (banded && banded.line);
  const marginLine =
    foundMarginLine &&
    refineMarginLine(foundMarginLine, selectTraceStrips(foundMarginLine.x), period.step);
  /**
   * Сторона, где разлиновка дошла до края профиля, — не найденное поле, а
   * ноль. Профиль начинается не с края кадра, а с защитной полосы, и край
   * области там означает только «линии идут дальше, чем видно»: поле, равное
   * полосе или первой видимой линии, выдало бы за поле обрезку кадра, и блок
   * встал бы вплотную к краю. Ноль отдаёт такую сторону фолбэку.
   *
   * Боковая граница — там, где кончаются горизонтальные линии (самый
   * внутренний конец по полосам), а у клетки, если вертикальные линии короче, —
   * крайняя вертикальная: берётся более узкая из двух. Иначе строка уходит в
   * полосу, где остались одни горизонтальные. Найденные боковые поля отступают
   * от границы внутрь на зазор: граница без линии поля сама служит полем.
   */
  const edgeGap = period.step * RULED_EDGE_GAP_SHARE;
  const rowBorders = refineRowBorders(image, skewAngle, period, ruledSpan, {
    left:
      columnRegion && columnRegion.start > 0
        ? columnResponse.origin + columnRegion.start
        : 0,
    right:
      columnRegion && columnRegion.end < columnResponse.values.length - 1
        ? columnResponse.origin + columnRegion.end + 1
        : image.width,
  });
  const leftBorder = Math.max(rowBorders.left, (gridColumns && gridColumns.left) || 0);
  const rightBorder = Math.min(
    rowBorders.right,
    (gridColumns && gridColumns.right) || image.width
  );
  const margins: PaperMargins = {
    top: ruledSpan && !ruledSpan.isAtProfileStart ? ruledSpan.first : 0,
    bottom: ruledSpan && !ruledSpan.isAtProfileEnd ? image.height - ruledSpan.last : 0,
    left: leftBorder > 0 ? leftBorder + edgeGap : 0,
    right: rightBorder < image.width ? image.width - rightBorder + edgeGap : 0,
  };
  const ruledEdges: RuledEdges = {
    top:
      ruledSpan && ruledSpan.isAtProfileStart
        ? { position: ruledSpan.first, strips: ruledSpan.firstStrips }
        : null,
    bottom:
      ruledSpan && ruledSpan.isAtProfileEnd
        ? { position: ruledSpan.last, strips: ruledSpan.lastStrips }
        : null,
  };
  const bendDetection = detectRulingBend(
    image,
    { step: period.step, firstLinePhase: period.phase, skewAngle, margins },
    toBendRegion(image, tangent, margins, rowBorders, marginLine)
  );

  return {
    isDetected: true,
    step: period.step,
    firstLinePhase: period.phase,
    skewAngle,
    kind: isGrid ? 'grid' : 'lined',
    margins,
    marginLineX: marginLine && marginLine.x,
    marginLineSide: marginLine && marginLine.side,
    bend: bendDetection.bend,
    perspective: null,
    bendFoundNodeShare: bendDetection.foundNodeShare,
    confidence: period.confidence,
    coreMargins: {
      ...margins,
      top: ruledCore && !ruledCore.isAtProfileStart ? ruledCore.first : 0,
      bottom: ruledCore && !ruledCore.isAtProfileEnd ? image.height - ruledCore.last : 0,
    },
    ruledEdges,
    bandedStage,
    marginLineReport: {
      coverage: banded?.coverage || 0,
      ratio: banded?.ratio || 0,
      stage: toMarginLineStage(meanMarginLine, marginLine),
      threshold: banded && banded.threshold,
      profileVeto: veto ? { isCalled: true, ...veto } : { isCalled: false },
      colourGate,
    },
    bandSteps,
    convergenceSeed,
    convergenceOrigin,
  };
};
