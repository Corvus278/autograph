/**
 * Край листа, у которого стоит вертикальная линия поля.
 */
export type MarginLineSide = 'left' | 'right';

/**
 * Вид разлиновки семьи листов.
 */
export type RulingKind = 'grid' | 'lined' | 'blank';

/**
 * Поля листа в канонических пикселях семьи.
 */
export type PaperMargins = {
  /**
   * Отступ от верха листа до области письма.
   */
  top: number;

  /**
   * Отступ от правого края.
   */
  right: number;

  /**
   * Отступ от низа.
   */
  bottom: number;

  /**
   * Отступ от левого края.
   */
  left: number;
};

/**
 * Каноническая разлиновка семьи. Все величины — в канонических пикселях
 * семьи: экземпляры приводятся к ним коэффициентом нормировки.
 */
export type PaperRuling = {
  /**
   * Вид разлиновки. `blank` — лист без линий, шаг задаёт пользователь.
   */
  kind: RulingKind;

  /**
   * Шаг разлиновки: расстояние между соседними горизонтальными линиями.
   */
  step: number;

  /**
   * Расстояние от верха листа до первой горизонтальной линии.
   */
  firstLineOffset: number;

  /**
   * Поля листа.
   */
  margins: PaperMargins;

  /**
   * Отступ вертикальной линии поля от левого края листа. `null` — линии поля
   * на листе нет.
   */
  marginLineX: number | null;
};

/**
 * Низкочастотное поле освещения листа: сетка нормированных яркостей, снятая с
 * фотографии пустого листа.
 */
export type LightingField = {
  /**
   * Число столбцов сетки.
   */
  gridWidth: number;

  /**
   * Число строк сетки.
   */
  gridHeight: number;

  /**
   * Яркости узлов сетки от 0 до 1, построчно сверху вниз. Нормированы на
   * самый светлый узел: у него ровно 1, поэтому поле описывает форму света, а
   * не абсолютную экспозицию снимка.
   */
  values: number[];

  /**
   * Размах яркости по листу: разница между светлой и тёмной частью в долях
   * самой светлой части. По нему решается пригодность поля.
   */
  contrast: number;

  /**
   * Пригодность поля к использованию. `false` — источник освещён равномерно
   * (скан), отрисовка берёт синтетическое освещение.
   */
  isUsable: boolean;
};

/**
 * Размер сетки поля освещения.
 */
export type LightingGrid = {
  /**
   * Число столбцов сетки.
   */
  gridWidth: number;

  /**
   * Число строк сетки.
   */
  gridHeight: number;
};

/**
 * Настройки извлечения поля освещения.
 */
export type ExtractLightingOptions = {
  /**
   * Число клеток вдоль длинной стороны листа.
   */
  gridSize?: number;

  /**
   * Порог размаха яркости, начиная с которого поле пригодно.
   */
  usableContrast?: number;
};

/**
 * Настройки извлечения карты текстуры.
 */
export type ExtractTextureOptions = {
  /**
   * Во сколько раз прореживать карту относительно фотографии. Целое число от
   * единицы; дробная часть отбрасывается. Не задано — прореживание берётся
   * таким, чтобы длинная сторона карты уложилась в её предел.
   */
  downscale?: number;

  /**
   * Доля отклонений, укладывающихся в размах карты.
   */
  amplitudePercentile?: number;
};

/**
 * Сырая карта высокочастотных отклонений: яркость пикселя минус
 * интерполированное поле освещения. Отделена от `PaperTexture`, потому что
 * считается чистой математикой без DOM, а кодирование в data URL требует
 * браузерного canvas.
 */
export type TextureMap = {
  /**
   * Ширина карты в пикселях.
   */
  width: number;

  /**
   * Высота карты в пикселях.
   */
  height: number;

  /**
   * Отклонения яркости, построчно сверху вниз. Ноль — пиксель ровно на поле
   * освещения, знак — темнее или светлее его.
   */
  values: Float32Array;

  /**
   * Размах отклонений в долях яркости, в который укладывается зерно бумаги.
   * Отклонения крупнее размаха есть всегда: разлиновка и соринки на порядок
   * темнее зерна, и если растянуть шкалу на них, само зерно ужмётся в
   * несколько уровней яркости карты.
   */
  amplitude: number;
};

/**
 * Высокочастотная карта текстуры бумаги: отклонения яркости от поля
 * освещения, свёрнутые в изображение для шейдера.
 */
export type PaperTexture = {
  /**
   * Карта отклонений как data URL полутонового изображения: 0 и 1 —
   * отклонение на `amplitude` в тёмную и светлую сторону, всё, что крупнее,
   * срезано границей. Нулевому отклонению отвечает 128/255, а не ровно 0.5:
   * середина восьмибитной шкалы не попадает на 0.5, и постоянное смещение в
   * полпроцента размаха неустранимо без второго канала.
   */
  src: string;

  /**
   * Ширина карты в пикселях.
   */
  width: number;

  /**
   * Высота карты в пикселях.
   */
  height: number;

  /**
   * Размах отклонений в долях яркости: множитель, которым шейдер разворачивает
   * значение пикселя карты обратно в отклонение яркости.
   */
  amplitude: number;
};

/**
 * Экземпляр листа: фотография и её измеренные характеристики. Разлиновку не
 * содержит — она принадлежит семье.
 */
export type PaperSheet = {
  /**
   * Идентификатор экземпляра, уникальный внутри приложения.
   */
  id: string;

  /**
   * Подпись экземпляра в списке.
   */
  label: string;

  /**
   * Фотография листа: путь от корня сайта у предустановленных, data URL у
   * пользовательских.
   */
  src: string;

  /**
   * Ширина фотографии в пикселях.
   */
  width: number;

  /**
   * Высота фотографии в пикселях.
   */
  height: number;

  /**
   * Угол наклона разлиновки в кадре в градусах. Положительный — линии идут
   * вниз слева направо. Фотография не выправляется: по этому углу
   * выкладывается текст.
   */
  skewAngle: number;

  /**
   * Шаг разлиновки, измеренный на фотографии, в её пикселях. Хранится рядом с
   * коэффициентом нормировки, чтобы нормировку можно было проверить и
   * пересчитать, не разбирая фотографию заново.
   */
  measuredStep: number;

  /**
   * Коэффициент приведения фотографии к каноническому шагу семьи: шаг,
   * измеренный на фотографии, умноженный на коэффициент, равен шагу семьи.
   */
  normalizeScale: number;

  /**
   * Смещение первой линии разлиновки от верха фотографии в пикселях
   * фотографии.
   */
  firstLinePhase: number;

  /**
   * Поле освещения. `null` — не извлекалось.
   */
  lighting: LightingField | null;

  /**
   * Карта текстуры бумаги. `null` — не извлекалась.
   */
  texture: PaperTexture | null;
};

/**
 * Семья листов: каноническая разлиновка и экземпляры-фотографии. Раскладка
 * текста считается по разлиновке семьи, поэтому смена экземпляра не
 * перекладывает текст.
 */
export type PaperFamily = {
  /**
   * Идентификатор семьи.
   */
  id: string;

  /**
   * Подпись семьи в списке.
   */
  label: string;

  /**
   * Ширина канонического листа в пикселях.
   */
  width: number;

  /**
   * Высота канонического листа в пикселях.
   */
  height: number;

  /**
   * Каноническая разлиновка.
   */
  ruling: PaperRuling;

  /**
   * Экземпляры семьи. Пустым не бывает: семья без фотографий нечем
   * отрисовывается.
   */
  sheets: PaperSheet[];
};

/**
 * Полутоновая выжимка изображения листа — вход всех измерений. Отделена от
 * DOM: анализ тестируется на сгенерированных массивах без браузера.
 */
export type SheetImageData = {
  /**
   * Ширина в пикселях.
   */
  width: number;

  /**
   * Высота в пикселях.
   */
  height: number;

  /**
   * Яркости пикселей от 0 (чёрный) до 1 (белый), построчно сверху вниз.
   */
  luminance: Float32Array;
};

/**
 * Найденная на фотографии разлиновка вместе с признаком удачи: неудача не
 * отбрасывает фотографию, а включает ручной ввод.
 */
export type RulingDetection = {
  /**
   * Найден ли шаг разлиновки.
   */
  isDetected: boolean;

  /**
   * Измеренный шаг разлиновки в пикселях фотографии. `0` — не найден.
   */
  step: number;

  /**
   * Смещение первой линии от верха фотографии в пикселях фотографии.
   */
  firstLinePhase: number;

  /**
   * Найденный вид разлиновки: `grid` — есть и вертикальные линии с тем же
   * шагом, `lined` — только горизонтальные.
   */
  kind: RulingKind;

  /**
   * Поля, найденные по границам области с линиями, в пикселях фотографии.
   */
  margins: PaperMargins;

  /**
   * Отступ вертикальной линии поля от левого края в пикселях фотографии.
   * `null` — линия поля не найдена.
   */
  marginLineX: number | null;

  /**
   * Край, у которого стоит линия поля. `null` — линии поля нет, синхронно с
   * `marginLineX`. Сторона нужна, потому что лист может быть снят как правая
   * половина разворота: тогда поле справа, и зеркалирование чётных страниц
   * должно это учитывать.
   */
  marginLineSide: MarginLineSide | null;

  /**
   * Уверенность в найденном шаге от 0 до 1: отношение пика автокорреляции к
   * фону. По ней решается `isDetected`.
   */
  confidence: number;
};

/**
 * Куда фотография листа ложится на страницу: прямоугольник в канонических
 * пикселях семьи. Отдельным типом, потому что считается чистой математикой по
 * нормировке экземпляра, а рисует по нему рендерер.
 */
export type SheetPlacement = {
  /**
   * Отступ левого края фотографии от левого края страницы. Отрицательный —
   * левая часть фотографии уходит за край и обрезается.
   */
  x: number;

  /**
   * Отступ верхнего края фотографии от верха страницы. Отрицательный — верх
   * фотографии обрезается.
   */
  y: number;

  /**
   * Ширина фотографии на странице в канонических пикселях.
   */
  width: number;

  /**
   * Высота фотографии на странице в канонических пикселях.
   */
  height: number;
};
