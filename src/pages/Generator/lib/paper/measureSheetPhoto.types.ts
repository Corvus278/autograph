import type { MarginLineReport, RulingBandedStage } from './detectRuling';
import type {
  LightingField,
  RulingKind,
  SheetOutline,
  SheetRulingSource,
  TextureMap,
} from './paper.types';

/**
 * Настройки измерения фотографии листа.
 */
export type SheetPhotoOptions = {
  /**
   * Вид разлиновки семьи. У чистого листа разлиновка не ищется.
   */
  kind: RulingKind;

  /**
   * Контур листа, заданный руками. Не передан — ищется на фотографии; `null` —
   * лист во весь кадр без поиска.
   */
  outline?: SheetOutline | null;
};

/**
 * Числа, по которым решено, хранить ли перспективу.
 */
export type SheetPhotoPerspectiveReport = {
  /**
   * Доля узлов «линия × полоса», где линия нашлась, от 0 до 1.
   */
  foundNodeShare: number;

  /**
   * Шаг у верхней найденной линии в середине вырезки по ширине, px. `0` —
   * трассу проложить не удалось.
   */
  topStep: number;

  /**
   * Шаг у нижней найденной линии в середине вырезки по ширине, px. `0` —
   * трассу проложить не удалось.
   */
  bottomStep: number;

  /**
   * Наибольшее расхождение перспективной и ровной гребёнки, px.
   */
  deviation: number;

  /**
   * Перспектива прошла проверку надёжности, но числа с выпрямленной копии не
   * взяты — разлиновка на ней не нашлась либо нашлась с наклоном, при котором
   * её фаза не пара наклону выпрямления, — и лист сохранён ровным.
   */
  isRectifiedRulingMissing: boolean;
};

/**
 * Отчёт полосовой ступени замера периода: что она сделала и с какими числами.
 * По ним сверяются пороги её согласия и порог дрейфа перспективы.
 */
export type SheetPhotoBandedReport = {
  /**
   * Что сделала ступень: не понадобилась, отказала или дала шаг. Несётся
   * отдельно от `steps`: пустые шаги у отказа и у незапущенной ступени одни и
   * те же, а отчёту замера различать их надо.
   */
  stage: RulingBandedStage;

  /**
   * Шаги согласившихся полос сверху вниз, px. Пусто у любой ступени, кроме
   * `measured`.
   */
  steps: number[];

  /**
   * Прирост шага от верхней согласившейся полосы к нижней, доля: тот самый
   * дрейф, который засев схождения и описывает. Меряется по полосам, а не
   * пересчитывается из засева по высоте вырезки: пороги, ради которых число
   * печатается, стоят на крайних линиях области с линиями, а не на кадре.
   * `0` — полоса одна или шагов нет вовсе.
   */
  drift: number;
};

/**
 * Всё, что измерение знает о своих решениях сверх самой разлиновки: отчёты
 * сборки профилей и замера листа печатают это, а не пересчитывают.
 */
export type SheetPhotoDiagnostics = {
  /**
   * Разлиновка найдена. У чистого листа — `false`.
   */
  isRulingDetected: boolean;

  /**
   * Уверенность поиска шага, от 0 до 1.
   */
  confidence: number;

  /**
   * Вид найденной разлиновки; `blank` — не найдена или не искалась.
   */
  kind: RulingKind;

  /**
   * Доля узлов области с линиями, где при измерении изгиба линия нашлась.
   */
  bendFoundNodeShare: number;

  /**
   * Отчёт измерения перспективы. `null` — перспектива не мерилась: разлиновка
   * не найдена.
   */
  perspective: SheetPhotoPerspectiveReport | null;

  /**
   * Отчёт полосовой ступени прохода по кадру — того, что засевает схождение в
   * поиск перспективы. `null` — разлиновка не мерилась вовсе: чистый лист.
   *
   * Проход по выпрямленной копии сюда не попадает: на ней шаг по построению
   * почти не плывёт, и её дрейф говорит о качестве выпрямления, а не о листе.
   */
  banded: SheetPhotoBandedReport | null;

  /**
   * Отчёт поиска линии поля того прохода, чья разлиновка ушла наружу: ступень,
   * охват полос, отношение глубин и имя связавшего порога. По нему
   * калибруется барьер и принимается разбор снимка, которого в пресет-паке
   * нет.
   */
  marginLine: MarginLineReport;
};

/**
 * Результат измерения фотографии листа. Все длины — в пикселях её кадра.
 */
export type SheetPhotoMeasurement = {
  /**
   * Разлиновка для сборки экземпляра: ненайденные поля — нули, шаг `0` —
   * разлиновка не найдена, лист уходит в ручной ввод.
   */
  source: SheetRulingSource;

  /**
   * Контур листа; `null` — лист во весь кадр.
   */
  outline: SheetOutline | null;

  /**
   * Поле освещения, измеренное только по бумаге.
   */
  lighting: LightingField;

  /**
   * Карта текстуры, измеренная только по бумаге.
   */
  textureMap: TextureMap;

  /**
   * Числа для отчётов.
   */
  diagnostics: SheetPhotoDiagnostics;
};
