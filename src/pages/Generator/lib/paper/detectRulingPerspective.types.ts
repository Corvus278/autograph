import type { RulingPerspective, SheetRuling } from './paper.types';

/**
 * Разлиновка ровного прохода, поверх которой ищется перспектива: по ней
 * трасса знает, где искать линии и какими номерами их звать.
 */
export type PerspectiveBaseRuling = Pick<
  SheetRuling,
  'step' | 'firstLinePhase' | 'skewAngle' | 'margins'
>;

/**
 * Кадр фотографии, в который попала вырезка: отступы её левого верхнего угла от
 * краёв кадра и размеры самого кадра в пикселях фотографии.
 *
 * Нужен проверке надёжности. Знаменатель модели держится вдали от нуля по всему
 * кадру, а не по одной вырезке: за вырезкой фотография продолжается, строки
 * страницы выкладываются по кадру целиком, и горизонт перспективы, оставшийся
 * снаружи вырезки, увёл бы их со страницы.
 */
export type PerspectiveFrame = {
  /**
   * Отступ вырезки от левого края кадра, px.
   */
  left: number;

  /**
   * Отступ вырезки от верхнего края кадра, px.
   */
  top: number;

  /**
   * Ширина кадра фотографии, px.
   */
  width: number;

  /**
   * Высота кадра фотографии, px.
   */
  height: number;
};

/**
 * Результат измерения перспективы. Величины — в пикселях того изображения,
 * которое ушло в детектор: ему достаётся вырезка внутри листа, и перевод в
 * кадр фотографии остаётся за вызывающей стороной.
 */
export type RulingPerspectiveDetection = {
  /**
   * Перспектива разлиновки. `null` — линии идут через равный шаг или
   * перспективу не удалось измерить надёжно.
   */
  perspective: RulingPerspective | null;

  /**
   * Наклон разлиновки в градусах. При найденной перспективе — уточнённый
   * подгонкой: наклон входит в те же пять параметров гребёнки, что и
   * схождение, и с чужим наклоном найденная перспектива ставит линии мимо.
   * При `perspective: null` — наклон ровного прохода без изменений.
   */
  skewAngle: number;

  /**
   * Шаг разлиновки в начале перспективы — в середине кадра вырезки. При
   * `perspective: null` — шаг ровного прохода без изменений.
   */
  step: number;

  /**
   * Высота линии с нулевым номером у левого края вырезки в координате вдоль
   * линий. Номера линий те же, что у ровного прохода. При `perspective: null`
   * — фаза ровного прохода без изменений.
   */
  firstLinePhase: number;

  /**
   * Доля узлов «линия × полоса», где линия нашлась, от 0 до 1. Есть и при
   * `null`: по ней видно, почему перспектива отброшена.
   */
  foundNodeShare: number;

  /**
   * Шаг разлиновки у верхней найденной линии в середине кадра по ширине, px.
   * `0` — трассу проложить не удалось.
   */
  topStep: number;

  /**
   * Шаг разлиновки у нижней найденной линии в середине кадра по ширине, px.
   * `0` — трассу проложить не удалось.
   */
  bottomStep: number;

  /**
   * Наибольшее расхождение перспективной и ровной гребёнки по области с
   * линиями, px. По нему решается, стоит ли перспектива хранения.
   */
  deviation: number;
};
