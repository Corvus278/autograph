/**
 * Провал линии в профиле полосы.
 */
export type LineDip = {
  /**
   * Координата линии вдоль профиля полосы в бинах.
   */
  position: number;

  /**
   * Глубина провала.
   */
  depth: number;
};

/**
 * Линия гребёнки в одной полосе: где трасса её ждала и что там нашлось.
 */
export type TracedLine = {
  /**
   * Предсказанная координата линии в бинах: у стартовой линии — её положение
   * в полосе, у остальных — продолжение трассы.
   */
  predicted: number;

  /**
   * Найденный провал; `null` — линии в окне у предсказания нет или она мельче
   * порога трассы.
   */
  dip: LineDip | null;
};

/**
 * Гребёнка ровного прохода, вдоль которой идёт трасса.
 */
export type TraceComb = {
  /**
   * Координата линии с нулевым номером в бинах профиля.
   */
  lineOffset: number;

  /**
   * Шаг ровного прохода в бинах.
   */
  step: number;

  /**
   * Наименьший номер прослеживаемой линии.
   */
  firstLine: number;

  /**
   * Наибольший номер прослеживаемой линии.
   */
  lastLine: number;

  /**
   * Номер линии, от которой ищется старт: у середины области отход линий от
   * ровной гребёнки наименьший.
   */
  middleLine: number;
};
