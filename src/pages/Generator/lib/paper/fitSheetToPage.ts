import type { PaperFamily, PaperSheet, SheetPlacement } from './paper.types';

/**
 * Экземпляр глазами укладки: только нормировка, фаза и размеры фотографии.
 * Остальные характеристики на положение листа не влияют.
 */
type FittedSheet = Pick<
  PaperSheet,
  'width' | 'height' | 'normalizeScale' | 'firstLinePhase' | 'skewAngle'
>;

/**
 * Семья глазами укладки: размеры канонического листа и его разлиновка.
 */
type FittedFamily = Pick<PaperFamily, 'width' | 'height' | 'ruling'>;

/**
 * Сколько градусов в радиане: наклон разлиновки хранится в градусах, а тангенс
 * считается от радиан.
 */
const DEGREES_IN_RADIAN = 180 / Math.PI;

/**
 * Наименьший шаг, по которому имеет смысл подгонять смещение. Ниже него
 * подгонка кратными шагами вырождается: перебор кандидатов растёт обратно
 * шагу, а выигрыш в покрытии меньше пикселя.
 */
const MIN_ALIGN_STEP = 1;

/**
 * Насколько покрытие должно вырасти, чтобы считаться лучше. Без порога
 * кандидаты, закрывающие страницу одинаково, сравниваются шумом последних
 * разрядов: покрытие складывается из смещения и длины листа, и у разных
 * смещений равенство выходит лишь с точностью до вычислительной погрешности —
 * а выбор между ними виден на странице сдвигом на целый шаг.
 */
const COVERAGE_EPSILON = 1e-6;

/**
 * Зажимает смещение так, чтобы лист закрыл страницу настолько, насколько
 * позволяет его длина. Разлиновка при этом не учитывается — этим путём идут
 * только листы без шага.
 *
 * @param offset — желаемое смещение
 * @param length — длина листа на странице
 * @param pageLength — длина страницы
 * @returns смещение, при котором лист лежит на странице
 */
const clampOffset = (offset: number, length: number, pageLength: number): number => {
  const slack = pageLength - length;

  return Math.max(Math.min(slack, 0), Math.min(offset, Math.max(slack, 0)));
};

/**
 * Какую часть страницы закрывает лист при заданном смещении.
 *
 * @param offset — смещение листа
 * @param length — длина листа на странице
 * @param pageLength — длина страницы
 * @returns длина закрытой части страницы
 */
const measureCoverage = (offset: number, length: number, pageLength: number): number => {
  return Math.max(0, Math.min(pageLength, offset + length) - Math.max(0, offset));
};

/**
 * Подгоняет смещение листа кратно шагу разлиновки: лист сдвигается на целое
 * число шагов, поэтому его линии остаются на канонических линиях страницы, и
 * из таких смещений берётся то, при котором лист закрывает наибольшую часть
 * страницы.
 *
 * Из равных по покрытию берётся смещение, при котором не открывается верх
 * страницы: там лежит первая строка, и полоса бумаги под ней заметнее, чем у
 * нижнего края.
 *
 * @param offset — смещение, при котором первая линия фотографии попадает на
 *   первую каноническую линию
 * @param step — канонический шаг разлиновки
 * @param length — длина листа на странице
 * @param pageLength — длина страницы
 * @returns смещение листа на странице
 */
const alignOffsetToRuling = (
  offset: number,
  step: number,
  length: number,
  pageLength: number
): number => {
  if (!Number.isFinite(step) || step < MIN_ALIGN_STEP) {
    return clampOffset(offset, length, pageLength);
  }

  /**
   * Отсчёт идёт от ближайшего смещения, не открывающего верх страницы: у
   * равных по покрытию кандидатов побеждает первый, а перебор поднимается
   * только вниз — сдвинуть лист выше первого кандидата покрытия не добавляет.
   */
  const start = offset - Math.ceil(offset / step) * step;
  let best = start;
  let bestCoverage = measureCoverage(start, length, pageLength);

  for (let index = 1; start + index * step < pageLength; index += 1) {
    const candidate = start + index * step;
    const coverage = measureCoverage(candidate, length, pageLength);

    if (coverage > bestCoverage + COVERAGE_EPSILON) {
      best = candidate;
      bestCoverage = coverage;
    }
  }

  return best;
};

/**
 * Куда фотография экземпляра ложится на страницу.
 *
 * Масштаб — коэффициент нормировки экземпляра: только при нём шаг разлиновки
 * на фотографии становится каноническим шагом семьи, по которому посчитана
 * раскладка. Растянуть фотографию по размеру страницы значило бы дать ей
 * собственный шаг, и строки поехали бы с линий тем сильнее, чем дальше от
 * начала страницы.
 *
 * По вертикали лист сдвигается так, чтобы его первая линия легла на первую
 * каноническую, а дальше — кратно шагу, если это закрывает больше страницы.
 * Всё, что вышло за края, обрезается страницей.
 *
 * Нехватку листа у края не растягиваем: под непокрытой полосой остаётся
 * подложка страницы. Растяжение вернуло бы ровно тот дефект, который здесь
 * лечится, а полоса означает, что фотография показывает меньше бумаги, чем
 * объявлено каноном семьи, — это правится мерой канона, а не отрисовкой.
 *
 * Фаза первой линии отсчитывается у левого края страницы — там же, где
 * рендерер ставит начало блока текста, — поэтому на отражённой странице к ней
 * добавляется наклон разлиновки во всю ширину страницы.
 *
 * По горизонтали лист прижимается к тому краю, от которого отсчитывается
 * текст: к левому на нечётной странице и к правому на отражённой. Своей фазы
 * по горизонтали экземпляр не несёт, а на отражённой странице разлиновка
 * вместе с линией поля уходит к противоположному краю — тем же отражением,
 * которым считается отступ блока.
 *
 * @param sheet — экземпляр с посчитанной нормировкой и фазой
 * @param family — семья, к канону которой приведён экземпляр
 * @param isMirrored — страница отражена: правая половина разворота
 * @returns прямоугольник фотографии в канонических пикселях семьи
 */
export const fitSheetToPage = (
  sheet: FittedSheet,
  family: FittedFamily,
  isMirrored: boolean
): SheetPlacement => {
  const { width: pageWidth, height: pageHeight, ruling } = family;
  const scale = sheet.normalizeScale > 0 ? sheet.normalizeScale : 1;
  const width = sheet.width * scale;
  const height = sheet.height * scale;
  const tilt = Math.tan(sheet.skewAngle / DEGREES_IN_RADIAN);

  /**
   * Размеров у фотографии может не быть: экземпляр пришёл из хранилища
   * неполным. Лист в этом случае кладётся во всю страницу — без размеров
   * нормировать нечего, а страница без фона хуже страницы с растянутым.
   */
  if (width <= 0 || height <= 0) {
    return { x: 0, y: 0, width: pageWidth, height: pageHeight };
  }

  /**
   * Фаза измерена у левого края фотографии, а лист отражается вокруг середины
   * страницы: линия, шедшая у левого края, оказывается у правого, и у левого
   * края её место занимает та же линия, опущенная на наклон во всю ширину
   * страницы. Не учесть это — и разлиновка съезжает тем сильнее, чем круче
   * снят лист: на паке это до половины шага.
   */
  const phaseAtPageLeft =
    sheet.firstLinePhase * scale + (isMirrored ? tilt * pageWidth : 0);

  return {
    x: isMirrored ? pageWidth - width : 0,
    y: alignOffsetToRuling(
      ruling.firstLineOffset - phaseAtPageLeft,
      ruling.step,
      height,
      pageHeight
    ),
    width,
    height,
  };
};
