/**
 * Параметры вложения страницы в сцену — то, что задаётся контролами группы
 * «Сцена для сохранения».
 */
export type SceneComposeParams = {
  /**
   * Поворот страницы в градусах.
   */
  rotate: number;

  /**
   * Сдвиг страницы по горизонтали в пикселях.
   */
  shiftX: number;

  /**
   * Сдвиг страницы по вертикали в пикселях.
   */
  shiftY: number;

  /**
   * Добавка к ширине вложенной страницы в пикселях.
   */
  scale: number;

  /**
   * Степень затемнения страницы, от 0 до 1.
   */
  darken: number;

  /**
   * Рисовать ли тень под страницей.
   */
  hasShadow: boolean;
};

/**
 * Куда и какого размера ложится страница внутри сцены.
 */
export type PagePlacement = {
  /**
   * Ширина вложенной страницы в пикселях.
   */
  width: number;

  /**
   * Высота вложенной страницы в пикселях.
   */
  height: number;

  /**
   * Отступ слева до левого края страницы.
   */
  x: number;

  /**
   * Отступ сверху до верхнего края страницы.
   */
  y: number;
};

export type FitPageParams = {
  /**
   * Ширина снимка страницы в пикселях.
   */
  pageWidth: number;

  /**
   * Высота снимка страницы в пикселях.
   */
  pageHeight: number;

  /**
   * Ширина сцены в пикселях.
   */
  sceneWidth: number;

  /**
   * Высота сцены в пикселях.
   */
  sceneHeight: number;

  /**
   * Добавка к ширине вложенной страницы в пикселях.
   */
  scale: number;
};
