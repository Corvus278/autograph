/**
 * Подпись числового значения настройки вместе с единицей: то, что видит
 * пользователь рядом со слайдером и что читает скринридер.
 */
export type ValueFormatter = (value: number) => string;

/**
 * Параметры записи числа.
 */
export type NumberFormatOptions = {
  /**
   * Сколько знаков после запятой оставить; хвостовые нули отбрасываются.
   */
  fractionDigits: number;

  /**
   * Показывать ли плюс у положительных чисел. У нуля знака нет в любом случае.
   */
  isSigned: boolean;
};
