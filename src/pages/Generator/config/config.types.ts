import type { PaperSheet } from '../lib/paper/paper.types';

/**
 * Встроенный рукописный шрифт. `family` совпадает с именем в `@font-face`.
 */
export type HandwritingFont = {
  /**
   * Значение `font-family`, оно же идентификатор в списке.
   */
  family: string;

  /**
   * Подпись в списке шрифтов.
   */
  label: string;
};

/**
 * Встроенный фон листа. Размеры фона задают размер страницы, поэтому лежат
 * рядом: по ним считается разбивка на страницы до загрузки картинки.
 */
export type PageBackground = {
  /**
   * Идентификатор фона в сторе.
   */
  id: string;

  /**
   * Подпись в списке фонов.
   */
  label: string;

  /**
   * Путь к картинке от корня сайта.
   */
  src: string;

  /**
   * Ширина картинки в пикселях.
   */
  width: number;

  /**
   * Высота картинки в пикселях.
   */
  height: number;
};

/**
 * Сцена, в которую вкладывается снимок страницы при сохранении.
 */
export type Scene = {
  /**
   * Идентификатор сцены в сторе.
   */
  id: string;

  /**
   * Подпись в списке сцен.
   */
  label: string;

  /**
   * Путь к картинке от корня сайта.
   */
  src: string;
};

/**
 * Границы числового параметра для слайдера.
 */
export type ParameterRange = {
  /**
   * Наименьшее допустимое значение.
   */
  min: number;

  /**
   * Наибольшее допустимое значение.
   */
  max: number;

  /**
   * Шаг изменения.
   */
  step: number;
};

/**
 * Размеры фотографии листа в пикселях.
 */
export type PhotoSize = {
  /**
   * Ширина фотографии в пикселях.
   */
  width: number;

  /**
   * Высота фотографии в пикселях.
   */
  height: number;
};

/**
 * Характеристики экземпляров, посчитанные заранее: ключ — идентификатор
 * семьи, значение — её экземпляры по порядку. Семья, которой в наборе нет,
 * остаётся с экземплярами без измерений.
 */
export type PaperSheetProfiles = Record<string, PaperSheet[]>;

/**
 * Экземпляр в том виде, в каком его пишет скрипт сборки: шаг, фаза и наклон
 * лежат только в разлиновке, иначе артефакт нёс бы их в двух местах, и места
 * могли бы разойтись.
 */
export type PaperSheetProfile = Omit<
  PaperSheet,
  'skewAngle' | 'measuredStep' | 'normalizeScale' | 'firstLinePhase'
>;

/**
 * Артефакт `public/paper/profiles.json`: то, что скрипт сборки посчитал по
 * фотографиям пресет-пака, включая разлиновку каждого экземпляра в пикселях
 * его фотографии.
 */
export type PaperProfilesArtifact = {
  /**
   * Версия формата артефакта. Растёт, когда меняется состав полей: старый
   * артефакт с чужой версией отбрасывается целиком, а не разбирается по
   * частям.
   */
  version: number;

  /**
   * Экземпляры по идентификатору семьи.
   */
  families: Record<string, PaperSheetProfile[]>;
};
