/**
 * Встроенный рукописный шрифт. `family` совпадает с именем в `@font-face`.
 */
export type HandwritingFont = {
  /**
   * Значение `font-family`, оно же идентификатор в списке.
   */
  family: string;

  /**
   * Подпись в списке шрифтов.
   */
  label: string;
};

/**
 * Встроенный фон листа. Размеры фона задают размер страницы, поэтому лежат
 * рядом: по ним считается разбивка на страницы до загрузки картинки.
 */
export type PageBackground = {
  /**
   * Идентификатор фона в сторе.
   */
  id: string;

  /**
   * Подпись в списке фонов.
   */
  label: string;

  /**
   * Путь к картинке от корня сайта.
   */
  src: string;

  /**
   * Ширина картинки в пикселях.
   */
  width: number;

  /**
   * Высота картинки в пикселях.
   */
  height: number;
};

/**
 * Сцена, в которую вкладывается снимок страницы при сохранении.
 */
export type Scene = {
  /**
   * Идентификатор сцены в сторе.
   */
  id: string;

  /**
   * Подпись в списке сцен.
   */
  label: string;

  /**
   * Путь к картинке от корня сайта.
   */
  src: string;
};

/**
 * Границы числового параметра для слайдера.
 */
export type ParameterRange = {
  /**
   * Наименьшее допустимое значение.
   */
  min: number;

  /**
   * Наибольшее допустимое значение.
   */
  max: number;

  /**
   * Шаг изменения.
   */
  step: number;
};
