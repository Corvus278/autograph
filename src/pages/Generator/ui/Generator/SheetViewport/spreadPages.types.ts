/**
 * Направление шага по страницам: 1 — вперёд, −1 — назад.
 */
export type PageDirection = 1 | -1;

/**
 * Страницы разворота, считая с нуля.
 */
export type SpreadPair = {
  /**
   * Левая страница — нечётная по счёту.
   */
  left: number;

  /**
   * Правая страница — чётная по счёту. `null` — последняя нечётная страница
   * осталась без пары.
   */
  right: number | null;
};
