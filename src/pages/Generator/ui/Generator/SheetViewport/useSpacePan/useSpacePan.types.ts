/**
 * Состояние панорамы для курсора области.
 */
export type SpacePanState = {
  /**
   * Пробел зажат: нажатие в области начнёт перетаскивание листа.
   */
  isPanReady: boolean;

  /**
   * Лист перетаскивается прямо сейчас.
   */
  isPanning: boolean;
};

/**
 * Откуда началось перетаскивание.
 */
export type PanStart = {
  /**
   * Указатель, захваченный перетаскиванием.
   */
  pointerId: number;

  /**
   * Горизонталь указателя в начале.
   */
  clientX: number;

  /**
   * Вертикаль указателя в начале.
   */
  clientY: number;

  /**
   * Горизонтальная прокрутка области в начале.
   */
  scrollLeft: number;

  /**
   * Вертикальная прокрутка области в начале.
   */
  scrollTop: number;
};
