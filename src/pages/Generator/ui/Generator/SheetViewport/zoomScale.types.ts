/**
 * Направление шага по лестнице масштаба: 1 — крупнее, −1 — мельче.
 */
export type ZoomDirection = 1 | -1;

/**
 * Вход расчёта вписанного масштаба.
 */
export type FitZoomInput = {
  /**
   * Ширина области просмотра в CSS-пикселях.
   */
  viewportWidth: number;

  /**
   * Высота области просмотра в CSS-пикселях.
   */
  viewportHeight: number;

  /**
   * Ширина того, что вписывается, в пикселях кадра листа.
   */
  pageWidth: number;

  /**
   * Высота того, что вписывается, в пикселях кадра листа.
   */
  pageHeight: number;

  /**
   * Отступ от края области до листа с каждой стороны в CSS-пикселях.
   */
  padding: number;
};
