export type LengthFieldProps = {
  /**
   * Подпись поля вместе с единицей.
   */
  label: string;

  /**
   * Введённое значение как есть. Строка, а не число: пока поле правят, оно
   * бывает пустым, и превращать пустоту в ноль на каждом нажатии нельзя.
   */
  value: string;

  /**
   * Нижняя граница ввода. Без неё отрицательное число принимается, и его
   * отвергает проверка при применении с сообщением.
   */
  min?: number;

  /**
   * Колбэк на правку значения.
   */
  onChange: (value: string) => void;
};
