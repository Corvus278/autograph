import type { PaperMargins } from '../../../../../lib/paper';

/**
 * Границы листа в полях диалога — отступы от краёв кадра как их ввёл
 * пользователь. Строки, а не числа: поле бывает пустым, пока его правят.
 */
export type SheetBoundsValues = {
  /**
   * Отступ листа от верхнего края кадра.
   */
  top: string;

  /**
   * Отступ листа от правого края кадра.
   */
  right: string;

  /**
   * Отступ листа от нижнего края кадра.
   */
  bottom: string;

  /**
   * Отступ листа от левого края кадра.
   */
  left: string;
};

/**
 * Разлиновка в полях диалога как её ввёл пользователь.
 */
export type SheetRulingValues = {
  /**
   * Шаг разлиновки.
   */
  step: string;

  /**
   * Смещение первой линии от верха фотографии.
   */
  firstLinePhase: string;

  /**
   * Верхнее поле.
   */
  marginTop: string;

  /**
   * Правое поле.
   */
  marginRight: string;

  /**
   * Нижнее поле.
   */
  marginBottom: string;

  /**
   * Левое поле.
   */
  marginLeft: string;
};

/**
 * Черновик диалога листа: всё, что применяется к листу только по «Сохранить»
 * или перемером.
 */
export type SheetDraft = {
  /**
   * Границы листа на фотографии.
   */
  bounds: SheetBoundsValues;

  /**
   * Разлиновка листа.
   */
  ruling: SheetRulingValues;

  /**
   * Лист без разлиновки: перемер не ищет на нём линии.
   */
  isBlank: boolean;
};

/**
 * Разлиновка, заданная руками. Все длины — в пикселях фотографии: пользователь
 * меряет их по своему снимку, и другой меры у листа нет.
 */
export type ManualRuling = {
  /**
   * Шаг разлиновки: расстояние между соседними линиями.
   */
  step: number;

  /**
   * Смещение первой линии от верха фотографии.
   */
  firstLinePhase: number;

  /**
   * Поля листа.
   */
  margins: PaperMargins;
};
