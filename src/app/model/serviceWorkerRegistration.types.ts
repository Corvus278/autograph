export type RegisterServiceWorkerOptions = {
  /**
   * Колбэк на появление новой версии, загруженной фоном: она ждёт активации,
   * страница продолжает работать на текущей.
   */
  onNeedRefresh: () => void;

  /**
   * Колбэк на завершение первой загрузки кэша: приложение открывается без
   * сети.
   */
  onOfflineReady: () => void;

  /**
   * Колбэк на отказ регистрации — запрет хранилища, исчерпанная квота,
   * недоступный `sw.js`. Приложение остаётся работоспособным в сети.
   */
  onRegisterError: (error: unknown) => void;
};

/**
 * Переход на загруженную новую версию: страница перезагружается, как только
 * новый service worker берёт управление. Аргумент `reloadPage` плагин не
 * использует и оставлен ради совместимости с его сигнатурой.
 */
export type UpdateServiceWorker = (reloadPage?: boolean) => Promise<void>;
