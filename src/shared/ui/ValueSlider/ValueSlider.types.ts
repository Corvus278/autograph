export type ValueSliderProps = {
  /**
   * Подпись контрола.
   */
  label: string;

  /**
   * Текущее значение параметра.
   */
  value: number;

  /**
   * Наименьшее допустимое значение.
   */
  min: number;

  /**
   * Наибольшее допустимое значение.
   */
  max: number;

  /**
   * Шаг изменения.
   */
  step: number;

  /**
   * Подпись значения с единицей: её видит пользователь рядом с названием и
   * читает скринридер вместо голого числа.
   */
  formatValue: (value: number) => string;

  /**
   * Колбэк на каждое изменение значения, в том числе посреди перетаскивания.
   */
  onChange: (value: number) => void;

  /**
   * Колбэк на окончательное значение: отпущенный бегунок или шаг клавишей.
   */
  onValueCommit?: (value: number) => void;

  /**
   * Контрол недоступен.
   */
  isDisabled?: boolean;

  /**
   * Дополнительные классы.
   */
  className?: string;
};
